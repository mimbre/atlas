defmodule AtlasRuntime.Backend.TcpListener do
  @moduledoc """
  The backend's loopback TCP listener (design §8.1, §9; S3 plan B1–B5): Bandit on
  `127.0.0.1` only, at the port `$ATLAS_RUNTIME_HOME/clients.json` names, serving the same
  generated router as `backend.sock`. It is reached only through the reachability path
  (`tailscale serve --https` on the mini, which ends TLS), never on a public address.
  Hand-written plumbing only. Like `AtlasRuntime.Backend.Listener` it is started from the
  host service, never from `AtlasRuntime.Application`, so never in the core release.

      AtlasRuntime.Backend.TcpListener.start_link(home: home, router: router)

  Options: `router:` (required: a router generated by
  `AtlasRuntimeBackend.Generator.Targets.Rest`), `home:` (default `$ATLAS_RUNTIME_HOME`),
  `ip:` (only `{127, 0, 0, 1}` is accepted; anything else is refused at init) and `name:`.
  Without `clients.json` it starts nothing (`:ignore`). A file that is invalid at start,
  or has the wrong mode or owner, stops the start with `{:clients, reason}`.

  Each request goes through, in this order:
  1. **Origin** (B5): any request carrying an `Origin` header is answered 403
     `origin-refused`, whatever its value (DNS-rebinding protection on loopback);
  2. **Bearer** (B4): `Authorization: Bearer <token>`. `clients.json` is read again for
     this request (B3, `AtlasRuntime.Backend.Clients`), and the token's SHA-256 is
     compared in constant time against every entry. A missing, malformed, unknown or
     disabled token, and a file that has become invalid or gone, get the same 401
     `unauthenticated` with `WWW-Authenticate: Bearer`. A broken file is logged in one
     line naming the problem, never its contents;
  3. **Client**: `conn.assigns.client = {"token:" <> name, rights}`, where `rights` is the
     entry's rights intersected with the contract's `rights :tcp` ceiling (a second line
     of defence after the file check);
  4. the router. Its 1 MiB body cap (400 `invalid`) applies here as on the socket.

  A stream (`GET /v1/events`) keeps a re-check in `conn.private`, which
  `AtlasRuntime.Backend.Events` calls at every heartbeat: the stream ends when the token
  was revoked or its rights changed (B3).

  The problem bodies come from the router (`__problem__/2`, from the contract); this
  module writes none. Neither the token nor its hash is ever logged or echoed. Two things
  keep a crash downstream from carrying the token into the log:
  - the guard removes the `authorization` header before it calls the router, so the
    conn a crash report prints (in the message and in `crash_reason`) has none;
  - Bandit also attaches its own conn, built before the guard ran, as `conn` metadata
    to the errors it logs. A logger primary filter (`log_filter/2`, added once at init)
    replaces the value of every `{"authorization", _}` header with `[redacted]` in
    the events of this listener (`plug: {Guard, _}` metadata), and only those.
  """
  use GenServer

  alias AtlasRuntime.Backend.Clients

  @loopback {127, 0, 0, 1}
  @filter :atlas_runtime_backend_tcp_authorization
  @redacted "[redacted]"

  def start_link(opts), do: GenServer.start_link(__MODULE__, opts, Keyword.take(opts, [:name]))

  @doc """
  What `host/service.exs` calls: `{:ok, pid}` when `clients.json` exists and is valid,
  `:none` when there is no file. Anything else raises, so the service does not start. The
  listener is linked to the caller once it runs (started unlinked first, so a refusal is
  this raise with its reason, not an exit signal).
  """
  def serve!(home, router) do
    case GenServer.start(__MODULE__, home: home, router: router) do
      {:ok, pid} ->
        Process.link(pid)
        {:ok, pid}

      :ignore ->
        :none

      {:error, {:clients, why}} ->
        raise "Runtime backend not listening on loopback TCP: #{why}"

      {:error, reason} ->
        raise "Runtime backend not listening on loopback TCP: #{inspect(reason)}"
    end
  end

  @doc "The address it listens on: `{ip, port}`."
  def address(server), do: GenServer.call(server, :address)

  @doc """
  The client the router gets for a loaded entry: `{"token:" <> name, rights}`, the
  entry's rights intersected with `ceiling` (in the ceiling's order).
  """
  def client(%{name: name, rights: rights}, ceiling),
    do: {"token:" <> name, Enum.filter(ceiling, &(&1 in rights))}

  @impl GenServer
  def init(opts) do
    Process.flag(:trap_exit, true)
    home = Keyword.get_lazy(opts, :home, fn -> System.fetch_env!("ATLAS_RUNTIME_HOME") end)
    router = Keyword.fetch!(opts, :router)
    ip = Keyword.get(opts, :ip, @loopback)
    ceiling = router.__rights__(:tcp)

    with :ok <- loopback(ip),
         :ok <- add_log_filter(),
         {:ok, uid} <- Clients.uid(),
         {:ok, %{port: port}} <- Clients.load(home, ceiling, uid),
         guard = %{home: home, router: router, ceiling: ceiling, uid: uid},
         {:ok, server} <-
           Bandit.start_link(
             plug: {__MODULE__.Guard, guard},
             ip: ip,
             port: port,
             startup_log: false
           ) do
      {:ok, %{server: server}}
    else
      :none -> :ignore
      {:error, why} when is_binary(why) -> {:stop, {:clients, why}}
      {:error, reason} -> {:stop, reason}
    end
  end

  @impl GenServer
  def handle_call(:address, _from, %{server: server} = state) do
    {:ok, address} = ThousandIsland.listener_info(server)
    {:reply, address, state}
  end

  @impl GenServer
  def handle_info({:EXIT, server, reason}, %{server: server} = state),
    do: {:stop, reason, %{state | server: nil}}

  def handle_info(_message, state), do: {:noreply, state}

  @impl GenServer
  def terminate(_reason, %{server: server}) do
    if server && Process.alive?(server), do: Supervisor.stop(server)
  end

  def terminate(_reason, _state), do: :ok

  defp loopback(@loopback), do: :ok
  defp loopback(ip), do: {:error, {:not_loopback, ip}}

  # Added once and kept: it is pure and only touches this listener's events, so a second
  # listener, or a restart, needs nothing more.
  defp add_log_filter do
    case :logger.add_primary_filter(@filter, {&__MODULE__.log_filter/2, nil}) do
      :ok -> :ok
      {:error, {:already_exist, @filter}} -> :ok
      {:error, reason} -> {:error, {:log_filter, reason}}
    end
  end

  @doc false
  # The logger primary filter: an event of this listener's Bandit (`plug: {Guard, _}`)
  # with the value of every `{"authorization", _}` header, at any depth, replaced by
  # `[redacted]`. It never raises (logger would drop a raising filter, and with it the
  # redaction): when the redaction fails, the event is replaced by a notice.
  def log_filter(%{meta: %{plug: {__MODULE__.Guard, _}} = meta, msg: msg} = event, _) do
    %{event | msg: scrub(msg), meta: scrub(meta)}
  rescue
    _ ->
      %{
        event
        | msg: {:string, "#{inspect(__MODULE__)}: a log event was dropped (redaction failed)"},
          meta: Map.take(event.meta, [:time, :gl, :pid, :domain])
      }
  end

  def log_filter(event, _), do: event

  defp scrub({"authorization", value}) when is_binary(value), do: {"authorization", @redacted}

  defp scrub(tuple) when is_tuple(tuple),
    do: tuple |> Tuple.to_list() |> scrub() |> List.to_tuple()

  defp scrub([head | tail]), do: [scrub(head) | scrub(tail)]
  defp scrub(map) when is_map(map), do: :maps.map(fn _key, value -> scrub(value) end, map)
  defp scrub(term), do: term

  defmodule Guard do
    @moduledoc false
    # Origin → Bearer → client → router, for every request on the TCP listener.
    @behaviour Plug

    require Logger

    alias AtlasRuntime.Backend.{Clients, TcpListener}

    # RFC 6750 b64token.
    @token ~r/\A[A-Za-z0-9\-._~+\/]+=*\z/

    @impl Plug
    def init(opts), do: opts

    @impl Plug
    def call(conn, %{router: router} = opts) do
      if Plug.Conn.get_req_header(conn, "origin") != [] do
        router.__problem__(:origin_refused, conn)
      else
        with {:ok, token} <- bearer(conn),
             {:ok, client} <- identify(token, opts) do
          # The router never sees the token: a crash downstream prints the conn, and
          # Bandit attaches it as log metadata (P2).
          conn
          |> Plug.Conn.delete_req_header("authorization")
          |> Plug.Conn.assign(:client, client)
          |> Plug.Conn.put_private(:atlas_runtime_recheck, fn ->
            identify(token, opts) == {:ok, client}
          end)
          |> router.call(router.init([]))
        else
          :error ->
            conn
            |> Plug.Conn.put_resp_header("www-authenticate", "Bearer")
            |> then(&router.__problem__(:unauthenticated, &1))
        end
      end
    end

    defp bearer(conn) do
      with ["Bearer " <> token] <- Plug.Conn.get_req_header(conn, "authorization"),
           true <- Regex.match?(@token, token) do
        {:ok, token}
      else
        _ -> :error
      end
    end

    # The file is read for every request (B3): no cache.
    defp identify(token, %{home: home, ceiling: ceiling, uid: uid}) do
      case Clients.load(home, ceiling, uid) do
        {:ok, %{clients: entries}} ->
          with {:ok, entry} <- Clients.authenticate(entries, token),
               do: {:ok, TcpListener.client(entry, ceiling)}

        :none ->
          Logger.error(
            "#{inspect(TcpListener)}: #{Clients.path(home)} is gone; TCP requests are refused"
          )

          :error

        {:error, why} ->
          Logger.error("#{inspect(TcpListener)}: #{why}; TCP requests are refused")
          :error
      end
    end
  end
end
