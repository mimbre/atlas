defmodule AtlasRuntime.Backend.Listener do
  @moduledoc """
  The backend's listener on the Unix socket `$ATLAS_RUNTIME_HOME/backend.sock` (design
  §8.1, D27): Bandit serving the generated router, mode 0600, removed when the listener
  stops. Hand-written plumbing only. It is started from the host service (not from
  `AtlasRuntime.Application`, so never in the core release), and leaves `runtime.sock`
  alone.

  Only the socket's owner can connect (mode 0600; agents' sandboxes deny the Runtime home,
  I8), so every client is that owner: `local:<name>`, where `<name>` is the user name of
  the Runtime process's uid (`id -un`; never `$USER` or `$LOGNAME`), with the socket
  listener's rights from the backend contracts the router serves (every work right,
  `choose_slot` and `choose_path` included, plus the operations rights `inspect` and
  `operate`, which only this listener grants; design §13.1 Q4, D44).
  The listener checks that the bound socket is owned by that uid. If the socket's mode is
  ever widened, the identity must come from the peer's credentials instead (design §1.8).

      AtlasRuntime.Backend.Listener.start_link(home: home, router: router)

  Options: `router:` (required: the one router generated by
  `AtlasRuntimeBackend.Generator.Targets.Rest` for all the backend contracts), `home:` (default `$ATLAS_RUNTIME_HOME`)
  and `name:`. A socket file left by a listener that is
  gone is replaced; one that still answers is not: the start fails with
  `:already_listening`.
  """
  use GenServer

  @socket "backend.sock"

  @doc "The socket's path in `home`."
  def path(home), do: Path.join(home, @socket)

  def start_link(opts), do: GenServer.start_link(__MODULE__, opts, Keyword.take(opts, [:name]))

  @impl GenServer
  def init(opts) do
    Process.flag(:trap_exit, true)
    home = Keyword.get_lazy(opts, :home, fn -> System.fetch_env!("ATLAS_RUNTIME_HOME") end)
    router = Keyword.fetch!(opts, :router)
    path = path(home)

    with {:ok, uid, name} <- owner(),
         client = {"local:" <> name, router.__rights__(:socket)},
         :ok <- clear(path),
         {:ok, server} <-
           Bandit.start_link(
             plug: {__MODULE__.Identity, {router, client}},
             ip: {:local, path},
             port: 0,
             startup_log: false
           ),
         :ok <- File.chmod(path, 0o600),
         :ok <- owned_by(path, uid, server) do
      {:ok, %{server: server, path: path, client: client}}
    else
      {:error, reason} -> {:stop, reason}
    end
  end

  @impl GenServer
  def handle_info({:EXIT, server, reason}, %{server: server} = state),
    do: {:stop, reason, %{state | server: nil}}

  def handle_info(_message, state), do: {:noreply, state}

  @impl GenServer
  def terminate(_reason, %{server: server, path: path}) do
    if server && Process.alive?(server), do: Supervisor.stop(server)
    File.rm(path)
  end

  # A socket nobody answers on is left over; anything else at the path is not ours.
  defp clear(path) do
    case File.lstat(path) do
      {:error, :enoent} ->
        :ok

      {:ok, %File.Stat{type: :other}} ->
        case :gen_tcp.connect({:local, path}, 0, [:binary, active: false], 1_000) do
          {:ok, socket} ->
            :gen_tcp.close(socket)
            {:error, :already_listening}

          {:error, _refused} ->
            File.rm(path)
        end

      {:ok, %File.Stat{type: type}} ->
        {:error, {:not_a_socket, path, type}}

      {:error, reason} ->
        {:error, reason}
    end
  end

  # The uid this process runs as, and its user name: from `id`, which reads the process's
  # own credentials and the user database, not the environment.
  defp owner do
    with {:ok, uid} <- id(["-u"]),
         {uid, ""} <- Integer.parse(uid),
         {:ok, name} <- id(["-un"]) do
      {:ok, uid, name}
    else
      _ -> {:error, :no_owner_name}
    end
  end

  defp id(args) do
    case System.cmd("id", args, stderr_to_stdout: true) do
      {out, 0} when out != "" -> {:ok, String.trim(out)}
      _ -> :error
    end
  rescue
    ErlangError -> :error
  end

  # The bound socket belongs to the process's uid, so its peers can only be that user.
  defp owned_by(path, uid, server) do
    case File.lstat(path) do
      {:ok, %File.Stat{uid: ^uid}} ->
        :ok

      other ->
        Supervisor.stop(server)
        File.rm(path)
        {:error, {:socket_not_owned, path, other}}
    end
  end

  defmodule Identity do
    @moduledoc false
    # Every request on the socket comes from its owner: the client the router reads.
    @behaviour Plug

    @impl Plug
    def init(opts), do: opts

    @impl Plug
    def call(conn, {router, client}),
      do: conn |> Plug.Conn.assign(:client, client) |> router.call(router.init([]))
  end
end
