defmodule AtlasRuntimeBackend.Generator.Targets.Rest.Runtime do
  @moduledoc """
  What a router generated by `AtlasRuntimeBackend.Generator.Targets.Rest` calls at run
  time: choosing a resource, reading query and header values and a JSON body, and
  building problem and event bodies. Plain functions on plain data; the Plug calls are in
  the generated code.
  """

  alias AtlasRuntimeBackend.Generator.Paths

  @doc """
  The route for a request: `routes` as the router has them (`%{key, method, segments,
  query, required}`), the request's method, path segments and query string. Gives
  `{:ok, key, path_params, query}` (`query` maps a declared parameter to its text),
  `:no_route`, or `{:error, [reason]}` when the path matches but its query fits no route.
  """
  def select(routes, method, path_info, query_string) do
    candidates = for r <- routes, r.method == method, do: {r, r.segments}

    case Paths.match(candidates, path_info) do
      [] ->
        :no_route

      matched ->
        with {:ok, given} <- query(query_string) do
          names = given |> Map.keys() |> MapSet.new()

          fitting =
            for {route, params} <- matched,
                MapSet.subset?(names, MapSet.new(route.query)),
                MapSet.subset?(MapSet.new(route.required), names),
                do: {route, params}

          # A route with required parameters is more specific than one without.
          case Enum.sort_by(fitting, fn {route, _} -> -length(route.required) end) do
            [{route, params} | _] ->
              {:ok, route.key, params, given}

            [] ->
              declared = matched |> Enum.flat_map(fn {r, _} -> r.query end) |> Enum.uniq()

              case Enum.sort(MapSet.to_list(names) -- declared) do
                [] ->
                  {:error,
                   [
                     "query parameters #{names |> Enum.sort() |> Enum.join(", ")} do not fit one resource"
                   ]}

                unknown ->
                  {:error, Enum.map(unknown, &"unknown query parameter #{inspect(&1)}")}
              end
          end
        end
    end
  end

  @doc "The query string as `%{name => text}`: `{:ok, map}` or `{:error, [reason]}` (a name given twice)."
  def query(""), do: {:ok, %{}}

  def query(query_string) do
    query_string
    |> URI.query_decoder()
    |> Enum.reduce_while({:ok, %{}}, fn {name, value}, {:ok, acc} ->
      if Map.has_key?(acc, name),
        do: {:halt, {:error, ["query parameter #{inspect(name)} is given twice"]}},
        else: {:cont, {:ok, Map.put(acc, name, value)}}
    end)
  rescue
    ArgumentError -> {:error, ["the query is not percent-encoded correctly"]}
  end

  @doc """
  A path, query or header value as the input field's type takes it: an integer or a
  boolean from its text; other types as text, which the input's `new/1` checks. Text
  that is no integer or boolean stays text, so `new/1` reports it.
  """
  def coerce(:integer, text) do
    case Integer.parse(text) do
      {integer, ""} -> integer
      _ -> text
    end
  end

  def coerce(:boolean, "true"), do: true
  def coerce(:boolean, "false"), do: false
  def coerce(_type, text), do: text

  @doc """
  A request body as the input's fields: `fields` are the field names it may hold (text),
  or `nil` when the resource takes no body. An empty body is `{}`. Gives `{:ok, map}` or
  `{:error, [reason]}`.
  """
  def body(nil, ""), do: {:ok, %{}}
  def body(nil, _binary), do: {:error, ["this resource takes no body"]}
  def body(_fields, ""), do: {:ok, %{}}

  def body(fields, binary) do
    case JSON.decode(binary) do
      {:ok, map} when is_map(map) ->
        case Enum.sort(Map.keys(map) -- fields) do
          [] -> {:ok, map}
          unknown -> {:error, Enum.map(unknown, &"the body has no field #{inspect(&1)}")}
        end

      {:ok, _other} ->
        {:error, ["the body is no JSON object"]}

      {:error, _reason} ->
        {:error, ["the body is no JSON"]}
    end
  end

  @doc "A problem+json body (RFC 9457): `type`, `title` and `status`, then the outcome's fields."
  def problem(status, type, title, fields \\ %{}),
    do: Map.merge(fields, %{"type" => type, "title" => title, "status" => status})

  @doc "The text of `{a.b}` placeholders in `template` from the dumped outcome; `nil` when one has no value."
  def template(template, dumped) do
    Regex.split(~r/\{[a-z0-9_.]+\}/, template, include_captures: true)
    |> Enum.reduce_while([], fn
      "{" <> rest = part, acc ->
        if String.ends_with?(rest, "}") do
          path = rest |> String.trim_trailing("}") |> String.split(".")

          case get_in(dumped, path) do
            nil -> {:halt, nil}
            value -> {:cont, [acc, encode_segment(to_string(value))]}
          end
        else
          {:cont, [acc, part]}
        end

      part, acc ->
        {:cont, [acc, part]}
    end)
    |> case do
      nil -> nil
      iodata -> IO.iodata_to_binary(iodata)
    end
  end

  @doc "A header's value from a field's dumped value; `nil` stays `nil` (no header)."
  def header_text(nil), do: nil
  def header_text(value) when is_binary(value), do: value
  def header_text(value), do: to_string(value)

  @doc "One Server-Sent Events frame: `event:`, `id:` when there is one, and the JSON as `data:`."
  def frame(event, id, data) do
    id_line = if is_nil(id), do: [], else: ["id: ", Integer.to_string(id), "\n"]
    ["event: ", event, "\n", id_line, "data: ", JSON.encode!(data), "\n\n"]
  end

  @doc """
  What a facade's answer that is no outcome means, the same for every contract:
  `{:not_permitted, right}` for a struct with exactly the fields `capability` and `right`
  (the client lacks the capability's right), `{:invalid, [reason]}` for one with exactly
  `capability` and `reasons` (the input does not validate), else `:none`.
  """
  def refusal(%{__struct__: _, capability: _, right: right} = value) when map_size(value) == 3,
    do: {:not_permitted, right}

  def refusal(%{__struct__: _, capability: _, reasons: reasons} = value)
      when map_size(value) == 3,
      do: {:invalid, Enum.map(List.wrap(reasons), &to_string/1)}

  def refusal(_value), do: :none

  defp encode_segment(value), do: URI.encode(value, &URI.char_unreserved?/1)
end
