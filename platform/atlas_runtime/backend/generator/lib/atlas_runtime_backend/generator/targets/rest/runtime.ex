defmodule AtlasRuntimeBackend.Generator.Targets.Rest.Runtime do
  @moduledoc """
  What a router generated by `AtlasRuntimeBackend.Generator.Targets.Rest` calls at run
  time: choosing a resource, reading query and header values and a JSON body, and
  building problem and event bodies. Plain functions on plain data; the Plug calls are in
  the generated code.
  """

  alias AtlasRuntimeBackend.Generator.Paths

  @doc """
  The route for a request: `routes` as the router has them (`%{key, method, segments,
  query, required}`), the request's method, path segments and query string. Gives
  `{:ok, key, path_params, query}` (`query` maps a declared parameter to its text),
  `:no_route`, or `{:error, [reason]}` when the path matches but its query fits no route.
  """
  def select(routes, method, path_info, query_string) do
    candidates = for r <- routes, r.method == method, do: {r, r.segments}

    case Paths.match(candidates, path_info) do
      [] ->
        :no_route

      matched ->
        declared = matched |> Enum.flat_map(fn {r, _} -> r.query end) |> Enum.uniq()

        with {:ok, given} <- query(query_string, declared) do
          names = given |> Map.keys() |> MapSet.new()

          fitting =
            for {route, params} <- matched,
                MapSet.subset?(names, MapSet.new(route.query)),
                MapSet.subset?(MapSet.new(route.required), names),
                do: {route, params}

          # A route with required parameters is more specific than one without.
          case Enum.sort_by(fitting, fn {route, _} -> -length(route.required) end) do
            [{route, params} | _] ->
              {:ok, route.key, params, given}

            [] ->
              case Enum.sort(MapSet.to_list(names) -- declared) do
                [] ->
                  {:error,
                   [
                     "query parameters #{names |> Enum.sort() |> Enum.join(", ")} do not fit one resource"
                   ]}

                # An unknown name is request data: never repeated (D44).
                _unknown ->
                  {:error, ["the query has an unknown parameter"]}
              end
          end
        end
    end
  end

  @doc """
  The query string as `%{name => text}`: `{:ok, map}` or `{:error, [reason]}` (a name
  given twice). The reason names the parameter only when it is one of `declared`: any
  other name is request data, never repeated (D44).
  """
  def query(query_string, declared \\ [])
  def query("", _declared), do: {:ok, %{}}

  def query(query_string, declared) do
    query_string
    |> URI.query_decoder()
    |> Enum.reduce_while({:ok, %{}}, fn {name, value}, {:ok, acc} ->
      if Map.has_key?(acc, name),
        do: {:halt, {:error, [twice(name, declared)]}},
        else: {:cont, {:ok, Map.put(acc, name, value)}}
    end)
  rescue
    ArgumentError -> {:error, ["the query is not percent-encoded correctly"]}
  end

  defp twice(name, declared) do
    if name in declared,
      do: "query parameter #{inspect(name)} is given twice",
      else: "a query parameter is given twice"
  end

  @doc """
  A path, query or header value as the input field's type takes it: an integer or a
  boolean from its text; other types as text, which the input's `new/1` checks. Text
  that is no integer or boolean stays text, so `new/1` reports it.
  """
  def coerce(:integer, text) do
    case Integer.parse(text) do
      {integer, ""} -> integer
      _ -> text
    end
  end

  def coerce(:boolean, "true"), do: true
  def coerce(:boolean, "false"), do: false
  def coerce(_type, text), do: text

  @doc """
  A request body as the input's fields: `fields` are the field names it may hold (text),
  or `nil` when the resource takes no body. An empty body is `{}`. Gives `{:ok, map}` or
  `{:error, [reason]}`.
  """
  def body(nil, ""), do: {:ok, %{}}
  def body(nil, _binary), do: {:error, ["this resource takes no body"]}
  def body(_fields, ""), do: {:ok, %{}}

  def body(fields, binary) do
    case JSON.decode(binary) do
      {:ok, map} when is_map(map) ->
        case Enum.sort(Map.keys(map) -- fields) do
          [] -> {:ok, map}
          # An unknown key is request data: never repeated (D44).
          _unknown -> {:error, ["the body has an unknown field"]}
        end

      {:ok, _other} ->
        {:error, ["the body is no JSON object"]}

      {:error, _reason} ->
        {:error, ["the body is no JSON"]}
    end
  end

  @doc "A problem+json body (RFC 9457): `type`, `title` and `status`, then the outcome's fields."
  def problem(status, type, title, fields \\ %{}),
    do: Map.merge(fields, %{"type" => type, "title" => title, "status" => status})

  @doc "The text of `{a.b}` placeholders in `template` from the dumped outcome; `nil` when one has no value."
  def template(template, dumped) do
    Regex.split(~r/\{[a-z0-9_.]+\}/, template, include_captures: true)
    |> Enum.reduce_while([], fn
      "{" <> rest = part, acc ->
        if String.ends_with?(rest, "}") do
          path = rest |> String.trim_trailing("}") |> String.split(".")

          case get_in(dumped, path) do
            nil -> {:halt, nil}
            value -> {:cont, [acc, encode_segment(to_string(value))]}
          end
        else
          {:cont, [acc, part]}
        end

      part, acc ->
        {:cont, [acc, part]}
    end)
    |> case do
      nil -> nil
      iodata -> IO.iodata_to_binary(iodata)
    end
  end

  @doc "A header's value from a field's dumped value; `nil` stays `nil` (no header)."
  def header_text(nil), do: nil
  def header_text(value) when is_binary(value), do: value
  def header_text(value), do: to_string(value)

  @doc "One Server-Sent Events frame: `event:`, `id:` when there is one, and the JSON as `data:`."
  def frame(event, id, data) do
    id_line = if is_nil(id), do: [], else: ["id: ", Integer.to_string(id), "\n"]
    ["event: ", event, "\n", id_line, "data: ", JSON.encode!(data), "\n\n"]
  end

  @doc "An entity tag (RFC 9110 §8.8.3) for an integer field: its decimal text, quoted."
  def etag(value) when is_integer(value), do: ~s("#{value}")

  @doc """
  Whether `If-None-Match` (the request's header values) holds `tag`, so the answer is
  304: a list of tags, compared weakly (RFC 9110 §13.1.2: `W/` is ignored), or `*`.
  No header is never a match.
  """
  def not_modified?(values, tag) do
    values
    |> Enum.flat_map(&String.split(&1, ","))
    |> Enum.map(&String.trim/1)
    |> Enum.any?(&(&1 == "*" or opaque(&1) == opaque(tag)))
  end

  defp opaque("W/" <> tag), do: tag
  defp opaque(tag), do: tag

  @doc """
  What a facade's answer that is no outcome means, the same for every contract:
  `{:not_permitted, right}` for a struct with exactly the fields `capability` and `right`
  (the client lacks the capability's right), `{:invalid, [reason]}` for one with exactly
  `capability` and `reasons` (the input does not validate), else `:none`.
  """
  def refusal(%{__struct__: _, capability: _, right: right} = value) when map_size(value) == 3,
    do: {:not_permitted, right}

  def refusal(%{__struct__: _, capability: _, reasons: reasons} = value)
      when map_size(value) == 3,
      do: {:invalid, Enum.map(List.wrap(reasons), &to_string/1)}

  def refusal(_value), do: :none

  defp encode_segment(value), do: URI.encode(value, &URI.char_unreserved?/1)

  ## A streamed request body

  @chunk 1_048_576
  @read_timeout 60_000

  @doc """
  The limit a streamed body's `max_bytes: {module, function}` gave: a positive integer,
  else an `ArgumentError` (a contract's limit is never guessed).
  """
  def limit!(limit, _module, _function) when is_integer(limit) and limit > 0, do: limit

  def limit!(other, module, function),
    do:
      raise(
        ArgumentError,
        "#{inspect(module)}.#{function}() gave #{inspect(other)}, no positive number of bytes"
      )

  @doc """
  Whether a request's `Content-Type` values are exactly one, of `expected` (its type and
  subtype, compared without case; parameters such as `charset` aside).
  """
  def media_type?([value], expected) do
    value |> String.split(";") |> hd() |> String.trim() |> String.downcase() == expected
  end

  def media_type?(_values, _expected), do: false

  @doc "Whether a request's `Content-Length` values declare more than `limit` bytes."
  def longer?([value], limit) do
    case Integer.parse(String.trim(value)) do
      {length, ""} -> length > limit
      _ -> false
    end
  end

  def longer?(_values, _limit), do: false

  @doc """
  The request body of `conn` as a lazy stream of chunks, read at most `limit` bytes:
  `{ref, stream}`. Each element is the next chunk (at most 1 MiB), read with `read`
  (`Plug.Conn.read_body/2`, which the router passes) only when the stream is enumerated;
  nothing is read before.
  The conn it reads with is kept in the calling process under `ref`, so the stream must be
  enumerated in that process (else an `ArgumentError`); `uploaded/1` gives the conn after
  the last read. More than `limit` bytes, or a read that fails, raises
  `AtlasRuntimeBackend.Generator.Targets.Rest.BodyError` (`kind: :too_large` or
  `:unreadable`). Once the body has ended, or failed, the stream is empty.
  """
  def upload(conn, limit, read) when is_integer(limit) and limit > 0 and is_function(read, 2) do
    ref = make_ref()
    owner = self()

    Process.put({__MODULE__, ref}, %{
      conn: conn,
      read: 0,
      state: :open,
      limit: limit,
      reader: read
    })

    {ref, Stream.resource(fn -> ref end, &next(&1, owner), fn ref -> ref end)}
  end

  @doc """
  After the facade: `{conn, read?}`, the conn of the last read of `ref`'s body (the one to
  answer with) and whether the body was read to its end.
  """
  def uploaded(ref) do
    %{conn: conn, state: state} = Process.get({__MODULE__, ref})
    {conn, state == :ended}
  end

  @doc "Forgets `ref`'s body: a stream read after this raises an `ArgumentError`."
  def discard(ref) do
    Process.delete({__MODULE__, ref})
    :ok
  end

  defp next(ref, owner) do
    if self() != owner,
      do:
        raise(
          ArgumentError,
          "a request body is read in the process that took the request, not in #{inspect(self())}"
        )

    case Process.get({__MODULE__, ref}) do
      nil ->
        raise ArgumentError, "the request body is read after its request was answered"

      %{state: state} when state in [:ended, :failed] ->
        {:halt, ref}

      %{conn: conn, read: read, limit: limit, reader: reader} = body ->
        # One byte past the limit is enough to know the body is too large.
        length = min(@chunk, limit - read + 1)

        case reader.(conn, length: length, read_length: length, read_timeout: @read_timeout) do
          {status, data, conn} when status in [:ok, :more] ->
            read = read + byte_size(data)

            if read > limit do
              Process.put({__MODULE__, ref}, %{body | conn: conn, read: read, state: :failed})

              raise AtlasRuntimeBackend.Generator.Targets.Rest.BodyError,
                kind: :too_large,
                ref: ref
            end

            state = if status == :ok, do: :ended, else: :open
            Process.put({__MODULE__, ref}, %{body | conn: conn, read: read, state: state})
            {if(data == "", do: [], else: [data]), ref}

          {:error, _reason} ->
            Process.put({__MODULE__, ref}, %{body | state: :failed})

            raise AtlasRuntimeBackend.Generator.Targets.Rest.BodyError,
              kind: :unreadable,
              ref: ref
        end
    end
  end
end

defmodule AtlasRuntimeBackend.Generator.Targets.Rest.BodyError do
  @moduledoc """
  Raised while a streamed request body is read (see
  `AtlasRuntimeBackend.Generator.Targets.Rest`): `kind` is `:too_large` (more bytes than
  the resource's `max_bytes`) or `:unreadable` (the read failed: the client went away or
  was too slow). A facade lets it pass; the router answers it. Its message names no
  request data.
  """
  defexception [:kind, :ref]

  @impl true
  def message(%{kind: :too_large}), do: "the request body is larger than its limit"
  def message(%{kind: _}), do: "the request body could not be read to its end"
end
