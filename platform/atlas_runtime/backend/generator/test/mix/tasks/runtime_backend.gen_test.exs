defmodule AtlasRuntimeBackend.Generator.Example.Fewer do
  @moduledoc "The example contract without its count resource: one resource removed."
  use AtlasRuntimeBackend.Generator.Schema

  version "1.0.0"
  boundary AtlasRuntimeBackend.Generator.Example.Boundary

  expose [:lend, :find_book, :search, :list_books, :give_back, :watch]
  not_exposed [:audit, :count, :scan, :deposit]

  rights :socket, [:lend, :browse]
  rights :guest, [:browse]

  event :book, :book_changed, id: :sequence
  event :tick, :tick
  event :restart, :restart, id: :current_sequence

  target :rest do
    resource :post, "/v1/books",
      capability: :lend,
      body: :input,
      header: ["Request-Key": :request_key]

    resource :get, "/v1/books/:book_id", capability: :find_book
    resource :get, "/v1/books", capability: :search, query: [title: :title]

    resource :get, "/v1/books",
      capability: :list_books,
      query: [condition: :condition, limit: :limit, lent: :lent]

    resource :post, "/v1/books/:book_id/return", capability: :give_back, body: [:note, :hurry]

    stream "/v1/events",
      capability: :watch,
      events: [:book, :tick, :restart],
      resume_header: "Last-Event-ID",
      into: :from,
      open: [watching: nil, restart: :restart]

    status :lent, 201, body: :book, header: [location: "/v1/books/{book.book_id}"]
    status :busy, 503, type: "busy", header: ["Retry-After": :retry_after]

    status :refused,
      by: :reason,
      cases: [
        invalid: {400, "invalid"},
        taken: {409, "taken"},
        not_permitted: {403, "not-permitted"}
      ]

    status :found, 200, body: :book
    status :missing, 404, type: "not-found"
    status :listed, 200
    status :returned, 200

    error :invalid, 400, type: "invalid"
    error :not_permitted, 403, type: "not-permitted"
    error :no_route, 404, type: "no-route"
  end
end

defmodule Mix.Tasks.RuntimeBackend.GenTest do
  # Sets the application's config, so not async.
  use ExUnit.Case

  alias AtlasRuntimeBackend.Generator.Header

  @moduletag :tmp_dir
  @app :atlas_runtime_backend_generator
  # OpenAPI 3.1 §4.8.1: the root's fixed fields; anything else must be an x- extension.
  @openapi_root ~w(openapi info jsonSchemaDialect servers paths webhooks components security
                   tags externalDocs)

  setup %{tmp_dir: dir} do
    Application.put_env(@app, :contract, AtlasRuntimeBackend.Generator.Example.Api)
    Application.put_env(@app, :targets, json: dir)
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :targets], do: Application.delete_env(@app, key)
      Mix.shell(Mix.Shell.IO)
    end)

    %{json: Path.join(dir, "api.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.RuntimeBackend.Gen.run(args)

  test "writes the contract's file, named after it, with its header; --check passes after",
       %{tmp_dir: dir, json: json} do
    gen()
    assert File.ls!(dir) == ["api.json"]

    assert "{\n  \"x-comment\": \"Generated by atlas (mix runtime_backend.gen). Do not edit: change " <>
             _ = File.read!(json)

    assert File.read!(json) =~ "test/support/example_api.ex and regenerate."
    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "the target's name: option names the file", %{tmp_dir: dir} do
    Application.put_env(@app, :targets, json: {dir, name: "lending"})
    gen()
    assert File.ls!(dir) == ["lending.json"]
  end

  test "--check fails on a stale file and writes nothing", %{json: json} do
    gen()
    File.write!(json, String.replace(File.read!(json), "/v1/books", "/v1/bookz"))
    assert_raise Mix.Error, ~r/out of date.*api.json/, fn -> gen(["--check"]) end
    assert File.read!(json) =~ "/v1/bookz"
  end

  test "--check fails on a missing file", %{json: json} do
    assert_raise Mix.Error, ~r/out of date.*api.json/, fn -> gen(["--check"]) end
    refute File.exists?(json)
  end

  test "a file with the header that no target writes is left over", %{tmp_dir: dir, json: json} do
    gen()
    old = Path.join(dir, "old.json")
    File.write!(old, File.read!(json))
    assert_raise Mix.Error, ~r/old.json \(left over\)/, fn -> gen(["--check"]) end
    gen()
    refute File.exists?(old)
    gen(["--check"])
  end

  test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, json: json} do
    File.write!(json, "{\n  \"mine\": true\n}\n")
    notes = Path.join(dir, "notes.json")
    File.write!(notes, "{\n  \"note\": \"Generated by atlas, they say\"\n}\n")
    assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
    assert File.read!(json) =~ "mine"
    File.rm!(json)
    gen()
    assert File.exists?(notes)
  end

  test "the header is recognised only when exact" do
    header = Header.put(".json", "lib/x.ex", "{\n  \"a\": 1\n}\n")
    assert Header.generated?(".json", header)
    refute Header.generated?(".json", String.replace(header, "runtime_backend.gen", "atlas.gen"))
    refute Header.generated?(".json", String.replace(header, "lib/x.ex", ""))
    refute Header.generated?(".swift", header)
    # A file written before the header became `x-comment` (P4 review F3) is still generated.
    assert Header.generated?(".json", String.replace(header, ~s("x-comment"), ~s("$comment")))
    refute Header.generated?(".json", String.replace(header, ~s("x-comment"), ~s("comment")))

    assert_raise ArgumentError, ~r/no header for .swift files/, fn ->
      Header.put(".swift", "x", "")
    end
  end

  test "an unknown target fails before anything is written", %{tmp_dir: dir} do
    Application.put_env(@app, :targets, swift: dir)

    assert_raise Mix.Error, ~r/unknown target :swift; known: \[:json, :openapi, :routes\]/, fn ->
      gen()
    end

    assert File.ls!(dir) == []
  end

  test "no contract configured" do
    Application.delete_env(@app, :contract)
    assert_raise Mix.Error, ~r/no contract/, fn -> gen() end
  end

  describe "configured in the project's mix.exs (runtime_backend:)" do
    test "names the file by the contract's key; root sets the header's path", %{tmp_dir: dir} do
      in_project(
        [
          contracts: [lending: AtlasRuntimeBackend.Generator.Example.Api],
          targets: [json: dir],
          root: "test"
        ],
        fn ->
          gen()
          assert File.ls!(dir) == ["lending.json"]

          assert File.read!(Path.join(dir, "lending.json")) =~
                   ~s(change support/example_api.ex and regenerate.)

          gen(["--check"])
          assert_received {:mix_shell, :info, ["generated files are up to date"]}
        end
      )
    end

    test "takes over from the application config", %{tmp_dir: dir} do
      other = Path.join(dir, "other")

      in_project(
        [contracts: [lending: AtlasRuntimeBackend.Generator.Example.Api], targets: [json: other]],
        fn ->
          gen()
          assert File.ls!(dir) == ["other"]
        end
      )
    end

    test "several contracts: a file each, with its own header", %{tmp_dir: dir} do
      both = [
        lending: AtlasRuntimeBackend.Generator.Example.Api,
        desk: AtlasRuntimeBackend.Generator.Example.DeskApi
      ]

      in_project([contracts: both, targets: [json: dir], root: "test"], fn ->
        gen()
        assert Enum.sort(File.ls!(dir)) == ["desk.json", "lending.json"]
        assert File.read!(Path.join(dir, "lending.json")) =~ "change support/example_api.ex"
        assert File.read!(Path.join(dir, "desk.json")) =~ "change support/example_desk.ex"
        assert File.read!(Path.join(dir, "desk.json")) =~ "/v1/desk/open"
        gen(["--check"])
        assert_received {:mix_shell, :info, ["generated files are up to date"]}
      end)

      # A contract taken out of the config leaves its file over.
      in_project(
        [contracts: Keyword.take(both, [:lending]), targets: [json: dir], root: "test"],
        fn ->
          assert_raise Mix.Error, ~r/desk.json \(left over\)/, fn -> gen(["--check"]) end
        end
      )
    end

    test "refuses a name twice, two contracts on one path, an unknown key, or no contract",
         %{tmp_dir: dir} do
      example = AtlasRuntimeBackend.Generator.Example.Api
      desk = AtlasRuntimeBackend.Generator.Example.DeskApi

      in_project([contracts: [a: example, a: desk], targets: [json: dir]], fn ->
        assert_raise Mix.Error, ~r/contract a is named twice/, fn -> gen() end
      end)

      in_project([contracts: [a: example, b: desk], targets: [json: {dir, name: "one"}]], fn ->
        assert_raise Mix.Error, ~r/two contracts write .*one.json/, fn -> gen() end
      end)

      in_project([contracts: [a: example], targets: [json: dir], contract: example], fn ->
        assert_raise Mix.Error, ~r/the keys are contracts:, targets: and root:/, fn -> gen() end
      end)

      in_project([targets: [json: dir]], fn ->
        assert_raise Mix.Error, ~r/expected contracts: \[name: Module, \.\.\.\], got nil/, fn ->
          gen()
        end
      end)

      assert File.ls!(dir) == []
    end
  end

  defp in_project(runtime_backend, fun) do
    module = :"Elixir.GenTestProject#{System.unique_integer([:positive])}"

    Module.create(
      module,
      quote do
        def project,
          do: [
            app: :gen_test_project,
            version: "0.0.0",
            runtime_backend: unquote(runtime_backend)
          ]
      end,
      Macro.Env.location(__ENV__)
    )

    Mix.Project.push(module, "nofile/mix.exs")

    try do
      fun.()
    after
      Mix.Project.pop()
    end
  end

  describe "the routes and openapi targets" do
    setup %{tmp_dir: dir} do
      Application.put_env(@app, :targets,
        routes: dir,
        openapi: {dir, security: [guest: :bearer]}
      )

      # In a folder named after the contract (api, from Example.Api), so that every contract
      # of one router has its own (S2).
      %{
        routes: Path.join([dir, "api", "routes.json"]),
        openapi: Path.join([dir, "api", "openapi.json"])
      }
    end

    test "write routes.json and openapi.json with their header; --check passes after",
         %{tmp_dir: dir, routes: routes, openapi: openapi} do
      gen()
      assert File.ls!(dir) == ["api"]
      assert File.ls!(Path.join(dir, "api")) |> Enum.sort() == ["openapi.json", "routes.json"]

      for path <- [routes, openapi] do
        assert Header.generated?(".json", File.read!(path))
        assert File.read!(path) =~ "test/support/example_api.ex and regenerate."
      end

      assert JSON.decode!(File.read!(openapi))["components"]["securitySchemes"]["guest"]

      # OpenAPI 3.1: the root holds only its fixed fields and x- extensions (P4 review F3).
      for key <- Map.keys(JSON.decode!(File.read!(openapi))),
          do: assert(key in @openapi_root or String.starts_with?(key, "x-"), key)

      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}
    end

    test "--check fails after a hand edit of either file", %{routes: routes, openapi: openapi} do
      for path <- [routes, openapi] do
        gen()
        File.write!(path, String.replace(File.read!(path), "/v1/books", "/v1/bookz"))
        name = Path.basename(path)
        assert_raise Mix.Error, ~r/out of date.*#{name}/, fn -> gen(["--check"]) end
        assert File.read!(path) =~ "/v1/bookz"
      end
    end

    test "--check fails after a resource is removed from the contract, until regenerated",
         %{tmp_dir: dir, routes: routes, openapi: openapi} do
      gen()
      # The contract's name is now fewer: its files go to fewer/, and api/'s are left over.
      Application.put_env(@app, :contract, AtlasRuntimeBackend.Generator.Example.Fewer)

      error = assert_raise Mix.Error, fn -> gen(["--check"]) end
      assert error.message =~ "fewer/routes.json"
      assert error.message =~ "fewer/openapi.json"
      assert error.message =~ "api/openapi.json (left over)"
      assert File.read!(openapi) =~ "/v1/count"

      gen()
      refute File.exists?(routes) or File.exists?(openapi)
      refute File.read!(Path.join([dir, "fewer", "routes.json"])) =~ "/v1/count"
      refute File.read!(Path.join([dir, "fewer", "openapi.json"])) =~ "/v1/count"
      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}
    end

    test "--check fails on a generated file no target writes any more",
         %{tmp_dir: dir, openapi: openapi} do
      gen()
      Application.put_env(@app, :targets, routes: dir)
      assert_raise Mix.Error, ~r/openapi.json \(left over\)/, fn -> gen(["--check"]) end
      assert File.exists?(openapi)
      gen()
      refute File.exists?(openapi)
      gen(["--check"])
    end
  end

  test "routes and openapi write each contract's files in its own folder, and contracts: " <>
         "gives a target its options per contract",
       %{tmp_dir: dir} do
    example = AtlasRuntimeBackend.Generator.Example.Api
    desk = AtlasRuntimeBackend.Generator.Example.DeskApi

    targets = [
      routes: dir,
      openapi: {dir, contracts: [:lending], title: "Lending", security: [guest: :bearer]},
      openapi: {dir, contracts: [:desk], title: "Desk"}
    ]

    in_project([contracts: [lending: example, desk: desk], targets: targets], fn ->
      gen()

      assert Path.wildcard(Path.join(dir, "**/*.json"))
             |> Enum.map(&Path.relative_to(&1, dir))
             |> Enum.sort() ==
               [
                 "desk/openapi.json",
                 "desk/routes.json",
                 "lending/openapi.json",
                 "lending/routes.json"
               ]

      lending = JSON.decode!(File.read!(Path.join([dir, "lending", "openapi.json"])))
      desk_doc = JSON.decode!(File.read!(Path.join([dir, "desk", "openapi.json"])))
      assert lending["info"]["title"] == "Lending"
      assert lending["components"]["securitySchemes"]["guest"]
      assert desk_doc["info"]["title"] == "Desk"
      refute Map.has_key?(desk_doc["components"], "securitySchemes")

      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}
    end)
  end

  test "contracts: naming no configured contract fails before anything is written",
       %{tmp_dir: dir} do
    example = AtlasRuntimeBackend.Generator.Example.Api

    in_project(
      [contracts: [lending: example], targets: [routes: {dir, contracts: [:lendng]}]],
      fn ->
        assert_raise Mix.Error, ~r/contracts: names :lendng; known: lending/, fn -> gen() end
      end
    )

    in_project(
      [contracts: [lending: example], targets: [routes: {dir, contracts: :lending}]],
      fn ->
        assert_raise Mix.Error, ~r/expected contracts: \[name, \.\.\.\]/, fn -> gen() end
      end
    )

    assert File.ls!(dir) == []
  end

  test "targets: [] writes nothing, and --check passes", %{tmp_dir: dir} do
    in_project([contracts: [work: AtlasRuntimeBackend.Generator.Example.Api], targets: []], fn ->
      gen()
      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}
    end)

    assert File.ls!(dir) == []
  end

  test "the targets read only a contract's data, not the schema's internals" do
    for path <- Path.wildcard("lib/**/*.ex") -- ["lib/atlas_runtime_backend/generator/schema.ex"] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")

      refute code =~ "AtlasRuntimeBackend.Generator.Schema.",
             "#{path} calls into AtlasRuntimeBackend.Generator.Schema"
    end
  end
end
