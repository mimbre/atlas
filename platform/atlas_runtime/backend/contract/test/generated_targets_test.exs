defmodule AtlasRuntimeBackend.GeneratedTargetsTest do
  use ExUnit.Case, async: true

  # The checked-in files of the work contract (`mix runtime_backend.gen --check` keeps them
  # current); each contract of the one router has its own folder.
  @dir Path.expand("../../targets/rest/work_api", __DIR__)
  @openapi @dir |> Path.join("openapi.json") |> File.read!() |> JSON.decode!()
  @routes @dir |> Path.join("routes.json") |> File.read!() |> JSON.decode!()

  defp operations,
    do: for({path, methods} <- @openapi["paths"], {method, op} <- methods, do: {method, path, op})

  defp types(response) do
    schema = response["content"]["application/problem+json"]["schema"]
    for s <- Map.get(schema, "oneOf", [schema]), do: s["properties"]["type"]["const"]
  end

  # OpenAPI 3.1 §4.8.1: the root's fixed fields; anything else must be an x- extension.
  @openapi_root ~w(openapi info jsonSchemaDialect servers paths webhooks components security
                   tags externalDocs)

  test "openapi.json's root has only OpenAPI fields and x- extensions (the header is x-comment)" do
    for key <- Map.keys(@openapi),
        do: assert(key in @openapi_root or String.starts_with?(key, "x-"), key)

    assert @openapi["x-comment"] =~ "Generated by atlas (mix runtime_backend.gen)"
    assert @routes["x-comment"] =~ "Generated by atlas (mix runtime_backend.gen)"
  end

  test "§8.1: the tcp listener's bearer scheme; a socket client needs no credentials" do
    assert %{"tcp" => %{"type" => "http", "scheme" => "bearer"}} =
             @openapi["components"]["securitySchemes"]

    assert @openapi["security"] == [%{}, %{"tcp" => []}]
    refute Map.has_key?(@openapi, "servers")
  end

  test "D44: only the socket names a path; a work's paths are optional in what clients get" do
    rights = Map.new(@routes["listeners"], &{&1["name"], &1["rights"]})
    assert "choose_path" in rights["socket"]
    refute "choose_path" in rights["tcp"]
    refute @openapi["components"]["securitySchemes"]["tcp"]["description"] =~ "choose_path"

    for name <- ["work_product_workspace", "resume_workspace"] do
      schema = @openapi["components"]["schemas"][name]
      assert Map.has_key?(schema["properties"], "path"), name
      refute "path" in schema["required"], name
    end
  end

  test "401 unauthenticated and 403 origin-refused on every operation; one branch per type" do
    for {method, path, op} <- operations() do
      assert types(op["responses"]["401"]) == ["unauthenticated"], "#{method} #{path}"
      assert "origin-refused" in types(op["responses"]["403"]), "#{method} #{path}"

      for {_code, r} <- op["responses"], r["content"]["application/problem+json"] do
        assert types(r) == Enum.uniq(types(r)), "#{method} #{path}: #{inspect(types(r))}"
      end
    end
  end

  test "§8.3: the conditional GET and the replayed header" do
    {_, _, get} =
      Enum.find(operations(), fn {m, p, _} -> {m, p} == {"get", "/v1/work/{work_id}"} end)

    assert %{"304" => not_modified} = get["responses"]
    refute Map.has_key?(not_modified, "content")

    assert Enum.count(operations(), fn {_, _, op} -> Map.has_key?(op["responses"], "304") end) ==
             1

    assert get_in(@routes, ["listeners"]) |> Enum.map(& &1["name"]) == ["socket", "tcp"]
    assert @openapi |> JSON.encode!() =~ ~s("idempotent-replayed")
  end

  test "S2 + S3: of the one router's contracts only work names the tcp listener, and its " <>
         "rights never include inspect, operate, choose_slot or choose_path" do
    tcp = Enum.find(@routes["listeners"], &(&1["name"] == "tcp"))
    assert tcp["rights"] == ["submit", "cancel", "read", "read_all"]

    for name <- ["operations_api", "history_api"] do
      dir = Path.expand("../../targets/rest/#{name}", __DIR__)
      routes = dir |> Path.join("routes.json") |> File.read!() |> JSON.decode!()
      openapi = dir |> Path.join("openapi.json") |> File.read!() |> JSON.decode!()

      assert Enum.map(routes["listeners"], & &1["name"]) == ["socket"], name
      refute Map.has_key?(openapi, "security"), name
      refute Map.has_key?(openapi["components"], "securitySchemes"), name
      assert openapi["openapi"] == "3.1.0"
      assert openapi["x-comment"] =~ "backend/contract/lib/#{name}.ex"
    end
  end
end
