defmodule Mix.Tasks.RuntimeBoundary.GenTest do
  # Sets the application's config, so not async.
  use ExUnit.Case

  alias AtlasRuntimeBoundary.Generator.Header

  @moduletag :tmp_dir
  @app :atlas_runtime_boundary_generator

  setup %{tmp_dir: dir} do
    Application.put_env(@app, :contract, AtlasRuntimeBoundary.Generator.Example)
    Application.put_env(@app, :targets, json: dir)
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :targets], do: Application.delete_env(@app, key)
      Mix.shell(Mix.Shell.IO)
    end)

    %{json: Path.join(dir, "example.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.RuntimeBoundary.Gen.run(args)

  test "writes the contract's file, named after it, with its header; a second run changes nothing",
       %{tmp_dir: dir, json: json} do
    gen()
    assert File.ls!(dir) == ["example.json"]

    assert "{\n  \"$comment\": \"Generated by atlas (mix runtime_boundary.gen). Do not edit: change " <>
             _ = File.read!(json)

    assert File.read!(json) =~ "test/support/example.ex and regenerate."
    refute File.read!(json) =~ ~s("wire")
    gen()
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "the target's name: option names the file", %{tmp_dir: dir} do
    Application.put_env(@app, :targets, json: {dir, name: "lending"})
    gen()
    assert File.ls!(dir) == ["lending.json"]
  end

  test "rewrites a file that differs from what the contract generates", %{json: json} do
    gen()
    File.write!(json, String.replace(File.read!(json), "shelf", "shelve"))
    gen()
    refute File.read!(json) =~ "shelve"
  end

  test "a file with the header that no target writes is left over", %{tmp_dir: dir, json: json} do
    gen()
    old = Path.join(dir, "old.json")
    File.write!(old, File.read!(json))
    gen()
    refute File.exists?(old)
  end

  test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, json: json} do
    File.write!(json, "{\n  \"mine\": true\n}\n")
    notes = Path.join(dir, "notes.json")
    File.write!(notes, "{\n  \"note\": \"Generated by atlas, they say\"\n}\n")
    assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
    assert File.read!(json) =~ "mine"
    File.rm!(json)
    gen()
    assert File.exists?(notes)
  end

  test "the header is recognised only when exact" do
    header = Header.put(".json", "lib/x.ex", "{\n  \"a\": 1\n}\n")
    assert Header.generated?(".json", header)
    refute Header.generated?(".json", String.replace(header, "runtime_boundary.gen", "atlas.gen"))
    refute Header.generated?(".json", String.replace(header, "lib/x.ex", ""))
    refute Header.generated?(".swift", header)

    assert_raise ArgumentError, ~r/no header for .swift files/, fn ->
      Header.put(".swift", "x", "")
    end
  end

  test "an unknown target fails before anything is written", %{tmp_dir: dir} do
    Application.put_env(@app, :targets, swift: dir)
    assert_raise Mix.Error, ~r/unknown target :swift; known: \[:json\]/, fn -> gen() end
    assert File.ls!(dir) == []
  end

  test "no contract configured" do
    Application.delete_env(@app, :contract)
    assert_raise Mix.Error, ~r/no contract/, fn -> gen() end
  end

  describe "configured in the project's mix.exs (runtime_boundary:)" do
    test "names the file by the contract's key; root sets the header's path", %{tmp_dir: dir} do
      in_project(
        [
          contracts: [lending: AtlasRuntimeBoundary.Generator.Example],
          targets: [json: dir],
          root: "test"
        ],
        fn ->
          gen()
          assert File.ls!(dir) == ["lending.json"]

          assert File.read!(Path.join(dir, "lending.json")) =~
                   ~s(change support/example.ex and regenerate.)

          gen()
          assert_received {:mix_shell, :info, ["generated files are up to date"]}
        end
      )
    end

    test "takes over from the application config", %{tmp_dir: dir} do
      other = Path.join(dir, "other")

      in_project(
        [contracts: [lending: AtlasRuntimeBoundary.Generator.Example], targets: [json: other]],
        fn ->
          gen()
          assert File.ls!(dir) == ["other"]
        end
      )
    end

    test "refuses an unknown key, or no contract", %{tmp_dir: dir} do
      example = AtlasRuntimeBoundary.Generator.Example

      in_project([contracts: [], targets: [json: dir]], fn ->
        assert_raise Mix.Error, ~r/expected contracts: \[name: Module\], got \[\]/, fn ->
          gen()
        end
      end)

      in_project([contracts: [a: example], targets: [json: dir], contract: example], fn ->
        assert_raise Mix.Error, ~r/the keys are contracts:, targets: and root:/, fn -> gen() end
      end)

      in_project([targets: [json: dir]], fn ->
        assert_raise Mix.Error, ~r/expected contracts: \[name: Module\], got nil/, fn -> gen() end
      end)

      assert File.ls!(dir) == []
    end
  end

  describe "several contracts in the project's mix.exs" do
    @example AtlasRuntimeBoundary.Generator.Example
    @catalogue AtlasRuntimeBoundary.Generator.Catalogue

    test "each contract writes its own file, whose header names its own contract file",
         %{tmp_dir: dir} do
      in_project(
        [contracts: [lending: @example, reading: @catalogue], targets: [json: dir]],
        fn ->
          gen()
          assert File.ls!(dir) |> Enum.sort() == ["lending.json", "reading.json"]

          lending = File.read!(Path.join(dir, "lending.json"))
          reading = File.read!(Path.join(dir, "reading.json"))
          assert Header.generated?(".json", lending) and Header.generated?(".json", reading)
          assert lending =~ "change test/support/example.ex and regenerate."
          assert reading =~ "change test/support/catalogue.ex and regenerate."
          assert lending =~ ~s("shortage") and not (lending =~ ~s("hold"))
          assert reading =~ ~s("hold") and not (reading =~ ~s("shortage"))

          gen()
          assert_received {:mix_shell, :info, ["generated files are up to date"]}
        end
      )
    end

    test "rewrites a stale or missing file of any contract", %{tmp_dir: dir} do
      in_project(
        [contracts: [lending: @example, reading: @catalogue], targets: [json: dir]],
        fn ->
          gen()
          reading = Path.join(dir, "reading.json")
          File.write!(reading, String.replace(File.read!(reading), "waitlist", "queue"))
          gen()
          assert File.read!(reading) =~ "waitlist"
          File.rm!(reading)
          gen()
          assert File.exists?(reading)
        end
      )
    end

    test "a removed contract's file is left over; gen removes it", %{tmp_dir: dir} do
      in_project(
        [contracts: [lending: @example, reading: @catalogue], targets: [json: dir]],
        fn ->
          gen()
        end
      )

      in_project([contracts: [lending: @example], targets: [json: dir]], fn ->
        assert File.ls!(dir) |> Enum.sort() == ["lending.json", "reading.json"]
        gen()
        assert File.ls!(dir) == ["lending.json"]
      end)
    end

    test "only the files no contract writes are left over", %{tmp_dir: dir} do
      in_project(
        [contracts: [lending: @example, reading: @catalogue], targets: [json: dir]],
        fn ->
          gen()
          old = Path.join(dir, "old.json")
          File.write!(old, File.read!(Path.join(dir, "reading.json")))
          gen()
          removed = "removed #{old} (left over)"
          assert_received {:mix_shell, :info, [^removed]}
          assert File.ls!(dir) |> Enum.sort() == ["lending.json", "reading.json"]
        end
      )
    end

    test "refuses two contracts with one name, or writing one file, before writing",
         %{tmp_dir: dir} do
      in_project(
        [contracts: [lending: @example, lending: @catalogue], targets: [json: dir]],
        fn ->
          assert_raise Mix.Error, ~r/two contracts are named lending/, fn -> gen() end
        end
      )

      in_project(
        [
          contracts: [lending: @example, reading: @catalogue],
          targets: [json: {dir, name: "all"}]
        ],
        fn ->
          assert_raise Mix.Error, ~r/contracts lending and reading both write .*all.json/, fn ->
            gen()
          end
        end
      )

      assert File.ls!(dir) == []
    end
  end

  defp in_project(runtime_boundary, fun) do
    module = :"Elixir.GenTestProject#{System.unique_integer([:positive])}"

    Module.create(
      module,
      quote do
        def project,
          do: [
            app: :gen_test_project,
            version: "0.0.0",
            runtime_boundary: unquote(runtime_boundary)
          ]
      end,
      Macro.Env.location(__ENV__)
    )

    Mix.Project.push(module, "nofile/mix.exs")

    try do
      fun.()
    after
      Mix.Project.pop()
    end
  end

  test "the targets read only a contract's data, not the schema's internals" do
    for path <- Path.wildcard("lib/**/*.ex") -- ["lib/atlas_runtime_boundary/generator/schema.ex"] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")

      refute code =~ "AtlasRuntimeBoundary.Generator.Schema.",
             "#{path} calls into AtlasRuntimeBoundary.Generator.Schema"
    end
  end
end
