defmodule Mix.Tasks.RuntimeModel.GenTest do
  # Sets the application's config, so not async.
  use ExUnit.Case

  @moduletag :tmp_dir
  @app :atlas_runtime_model_generator

  setup %{tmp_dir: dir} do
    Application.put_env(@app, :contracts, library: AtlasRuntimeModel.Generator.Example)
    Application.put_env(@app, :targets, json: dir)
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contracts, :targets], do: Application.delete_env(@app, key)
      Mix.shell(Mix.Shell.IO)
    end)

    %{json: Path.join(dir, "library.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.RuntimeModel.Gen.run(args)

  test "writes each file with its header; --check passes after", %{json: json} do
    gen()

    assert "{\n  \"$comment\": \"Generated by atlas (mix runtime_model.gen). Do not edit: change " <>
             _ = File.read!(json)

    assert File.read!(json) =~ "test/support/example.ex and regenerate."
    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "--check fails on a stale file and writes nothing", %{json: json} do
    gen()
    File.write!(json, String.replace(File.read!(json), "books/{book_id}.json", "books/{id}.json"))
    assert_raise Mix.Error, ~r/out of date.*library.json/, fn -> gen(["--check"]) end
    assert File.read!(json) =~ "books/{id}.json"
  end

  test "--check fails on a missing file", %{json: json} do
    assert_raise Mix.Error, ~r/out of date.*library.json/, fn -> gen(["--check"]) end
    refute File.exists?(json)
  end

  test "a file with the header that no target writes is left over", %{tmp_dir: dir} do
    gen()
    old = Path.join(dir, "old.json")
    File.write!(old, File.read!(Path.join(dir, "library.json")))
    assert_raise Mix.Error, ~r/old.json \(left over\)/, fn -> gen(["--check"]) end
    gen()
    refute File.exists?(old)
  end

  test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, json: json} do
    File.write!(json, "{\n  \"mine\": true\n}\n")
    notes = Path.join(dir, "notes.json")
    File.write!(notes, "{\n  \"note\": \"Generated by atlas, they say\"\n}\n")
    assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
    assert File.read!(json) =~ "mine"
    File.rm!(json)
    gen()
    assert File.exists?(notes)
  end

  test "an unknown target or no contract fails before anything is written", %{tmp_dir: dir} do
    Application.put_env(@app, :targets, swift: dir)
    assert_raise Mix.Error, ~r/unknown target :swift; known: \[:json\]/, fn -> gen() end
    Application.put_env(@app, :targets, json: dir)
    Application.delete_env(@app, :contracts)
    assert_raise Mix.Error, ~r/no contracts/, fn -> gen() end
    Application.put_env(@app, :contracts, library: String)
    assert_raise Mix.Error, ~r/is no model contract/, fn -> gen() end
    assert File.ls!(dir) == []
  end
end
