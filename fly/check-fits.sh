#!/usr/bin/env bash
# Whether rela runs this build's description (IS-Atlas-73). rela keeps the description it
# started with: start-test.sh copies schema.yaml and data-entry.yaml into its data folder
# on every start, so that copy is what it runs.
#
#   description.sh same   exit 0 when rela's data folder holds this build's description
#   description.sh fits   exit 0 when this build's description describes all of rela's
#                         data; else prints what it would leave without a description
#                         (a removed kind or field that still has data), one per line
#
# Takes the data folder and the binaries from ATLAS_RELA_DATA and ATLAS_RELA_BIN, as the
# other scripts here do. Reads only; the check runs on a copy of the data.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
root="${ATLAS_TEST_ROOT:-$HOME/.local/share/atlas/test}"
data="${ATLAS_RELA_DATA:-$root/rela}"
bin="${ATLAS_RELA_BIN:-$root/bin}"

# Input is the flat native-equivalent schema generated by config.py, never a root with includes.
case "${1:-}" in
  same)
    cmp -s "$here/schema.yaml" "$data/schema.yaml" &&
      cmp -s "$here/data-entry.yaml" "$data/data-entry.yaml"
    ;;

  fits)
    tmp="$(mktemp -d "${TMPDIR:-/tmp}/atlas-check-fits.XXXXXX")"
    trap 'rm -rf "$tmp"' EXIT
    cp "$here/schema.yaml" "$here/data-entry.yaml" "$tmp/"
    for part in entities relations; do
      if [ -d "$data/$part" ]; then cp -R "$data/$part" "$tmp/"; else mkdir -p "$tmp/$part"; fi
    done

    # A fresh copy has no drift ledger, so the scan names every orphan the data has.
    "$bin/rela" --project "$tmp" --quiet validate >/dev/null
    out="$("$bin/rela" --project "$tmp" --quiet migrate gc --scan 2>&1)"
    orphans="$(sed -n 's/^  \([A-Za-z0-9_.]*\)$/\1/p' <<<"$out")"

    # The scan finds fields a kind no longer has, not kinds or relations that are gone. A
    # kind's data is a folder named by its plural; a relation's, files <from>--<name>--<to>.md.
    for folder in "$tmp"/entities/*/; do
      [ -d "$folder" ] && [ -n "$(ls -A "$folder")" ] || continue
      name="$(basename "$folder")"
      grep -qE "^    plural: \"?$name\"?$" "$tmp/schema.yaml" ||
        orphans+=$'\n'"$name (a kind this build has no more)"
    done
    for name in $(ls "$tmp/relations" | sed -n 's/^.*--\([a-z0-9_]*\)--.*\.md$/\1/p' | sort -u); do
      grep -qE "^  $name:$" "$tmp/schema.yaml" ||
        orphans+=$'\n'"$name (a relation this build has no more)"
    done
    orphans="$(sed '/^$/d' <<<"$orphans")"

    if [ -n "$orphans" ]; then
      echo "$orphans"
      exit 1
    fi
    ;;

  *)
    echo "usage: description.sh same|fits" >&2
    exit 2
    ;;
esac
