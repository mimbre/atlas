defmodule AtlasFacts.MixProject do
  use Mix.Project

  def project do
    [
      app: :atlas_facts,
      version: "0.1.0",
      build_path: "../../_build",
      config_path: "../../config/config.exs",
      deps_path: "../../deps",
      lockfile: "../../mix.lock",
      elixir: "~> 1.18",
      elixirc_paths: elixirc_paths(Mix.env()),
      start_permanent: Mix.env() == :prod,
      deps: deps()
    ]
  end

  def application do
    [extra_applications: [:logger, :inets, :ssl, :public_key], mod: {AtlasFacts.Application, []}]
  end

  defp elixirc_paths(:test), do: ["lib", "test/support"]
  defp elixirc_paths(_), do: ["lib"]

  # Facts reaches the other layers only over the Bus.
  # The subflows are data, generated by model/dsl into model/targets/atlas/flows.json
  # and read at compile time (AtlasFacts.Subflows).
  defp deps,
    do: [
      {:atlas_bus, in_umbrella: true},
      {:rela_dsl, path: "../../../model/dsl"}
    ]
end
