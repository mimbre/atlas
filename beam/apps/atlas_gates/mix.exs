defmodule AtlasGates.MixProject do
  use Mix.Project

  def project do
    [
      app: :atlas_gates,
      version: "0.1.0",
      build_path: "../../_build",
      config_path: "../../config/config.exs",
      deps_path: "../../deps",
      lockfile: "../../mix.lock",
      elixir: "~> 1.18",
      start_permanent: Mix.env() == :prod,
      deps: deps()
    ]
  end

  # No application callback and no store: a caller asks Gates for a verdict, Gates evaluates
  # it and records it through Facts, from the caller's process.
  def application do
    [extra_applications: [:logger, :crypto]]
  end

  # Gates reaches the other layers only over the Bus. The gate definitions are data,
  # generated by flow/generator into flow/targets/atlas/flows.json and read at compile time.
  defp deps,
    do: [
      {:atlas_bus, in_umbrella: true},
      {:atlas_flow_generator, path: "../../../flow/generator"}
    ]
end
