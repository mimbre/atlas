defmodule Model.GoldenTest do
  use ExUnit.Case, async: true

  alias Model.AtlasEyra
  alias RelaDSL.{Atlas, Rela}

  # The committed target, read as the proof it is (no component reads it, D-0083).
  defmodule Committed do
    @moduledoc false
    @path Path.expand("../../targets/atlas/flows.json", __DIR__)
    @external_resource @path
    @data @path |> File.read!() |> JSON.decode!()

    def flows, do: @data["flows"]
    def composition, do: @data["composition"]
    def gates, do: @data["gates"]
    def rela_flows_sha256, do: @data["rela_flows_sha256"]

    def check_rela_flows(yaml) do
      if RelaDSL.Atlas.sha256(yaml) == rela_flows_sha256(),
        do: :ok,
        else: {:error, "flows.yaml is not the one generated with flows.json"}
    end
  end

  # test/golden/<file>.flows.yaml are the approved subflows (the design's
  # input-definitions/*.flows.yaml), with the version Rela gives each. A run keeps the
  # version it started with, so the generated file must keep them too. One intended change
  # (flow-compose-2): use_case's result field is design_status, not design, so its two
  # flows have new versions (were fb94ff2ad22d759e and cea573908d89e395).
  @versions [
    {"issue", [issue: "5e2320f6db243534"]},
    {"pull_request", [pull_request: "1235a3dae3c7e42b"]},
    {"pr_review", [pr_review: "f8969c0536e1442b"]},
    {"pr_test", [pr_test: "c3eae1a7a5eeea98"]},
    {"use_case",
     [design_and_accept: "0971d09c2b1a34ad", test_and_accept_use_case: "a207d811b03394f4"]},
    {"scene", [test_and_accept_scene: "8dc48c7180394ded"]},
    {"decision", [decide: "e2ad1048cd8a4748"]}
  ]

  defp below_header(text),
    do: text |> String.split("\n") |> Enum.drop_while(&(&1 =~ ~r/^#/)) |> Enum.join("\n")

  defp resolved,
    do: RelaDSL.Limits.resolve(AtlasEyra.__flows__(), AtlasEyra.__rela__(:gates), :prod)

  defp generated, do: Rela.flows_yaml(resolved())

  # The approved files, each below its comment header, as one flows.yaml in the
  # composition's order; blank lines between flows carry no meaning.
  defp approved do
    body =
      Enum.map_join(@versions, "", fn {file, _} ->
        "test/golden/#{file}.flows.yaml"
        |> File.read!()
        |> below_header()
        |> String.replace_prefix("flows:\n", "")
      end)

    "flows:\n" <> String.replace(body, ~r/\n\n+/, "\n")
  end

  test "the flows.yaml of the composition is the approved files, byte for byte below the headers" do
    assert generated() == approved()
  end

  test "the composition holds the eight subflows, in order" do
    names = for {_, flows} <- @versions, {name, _} <- flows, do: name
    assert Enum.map(AtlasEyra.__flows__(), & &1.name) == names
  end

  test "the committed target holds it, and each diagram shows its approved version" do
    yaml = File.read!("../../rela/flows.yaml")

    assert yaml =~
             ~r/\A# Generated by atlas \(mix model.gen\) from model\/contract\/compositions\/atlas_eyra.ex, /

    assert below_header(yaml) == generated()

    for {_, flows} <- @versions, {name, version} <- flows do
      assert File.read!("../targets/diagrams/#{name}.md") =~ "Rela flow version: `#{version}`"
    end
  end

  test "the committed flows.json is what the writer gives for the composition and every gate" do
    [open, header | rest] = String.split(File.read!("../targets/atlas/flows.json"), "\n")
    assert header =~ ~s(  "_generated": "Generated by atlas)

    assert header =~
             "from model/contract/compositions/atlas_eyra.ex, model/contract/software/issue.ex"

    assert header =~
             "model/contract/eyra/scene.ex, model/contract/foundation/decision.ex. Do not edit"

    assert Enum.join([open | rest], "\n") ==
             Atlas.flows_json(
               resolved(),
               AtlasEyra.__rela__(:gates),
               Committed.rela_flows_sha256(),
               AtlasEyra.__composition__()
             )
  end

  test "the committed composition is the compiled one; production applies none of it" do
    compiled = AtlasEyra.composition()
    no_nil = &Enum.map(&1, fn x -> Map.reject(x, fn {_, v} -> v == nil end) end)
    assert Committed.composition() == Map.update!(compiled, "links", no_nil)
    assert compiled["version"] == 1

    assert Enum.map(compiled["links"], &{&1["child"], &1["parent_subject"], &1["field"]}) == [
             {"pr_review", "pull_request", "review_outcome"},
             {"pr_test", "pull_request", "test_outcome"},
             {"pull_request", "issue", "pr_outcome"}
           ]

    assert Enum.map(compiled["counts"], &{&1["child"], &1["parent_subject"]}) == [
             {"issue", "use_case"},
             {"test_and_accept_use_case", "scene"}
           ]

    # Production selection is unchanged (only decide): no link or count has both ends
    # selected, so Flow applies none, and nothing refuses.
    for env <- [:prod, :test] do
      runner = AtlasFlow.Model.load(AtlasEyra, env, %{"decider" => "someone"})
      assert Map.keys(runner.config["selection"]) == ["decide"]
      assert runner.config["composition"] == %{"links" => [], "counts" => []}
      assert runner.refusal == nil
    end
  end

  test "the committed flows.json is bound to the committed flows.yaml" do
    assert Committed.check_rela_flows(File.read!("../../rela/flows.yaml")) == :ok
    assert {:error, _} = Committed.check_rela_flows(File.read!("test/golden/issue.flows.yaml"))
  end

  test "a running component reads the mechanisms and the gates" do
    flows = Committed.flows()
    states = flows["issue"]["states"]
    assert states["delivery_gate"]["spec"] == %{"gate" => "delivery_evidence", "version" => 1}

    assert Map.take(states["in_pr"], ~w(final label)) == %{
             "final" => false,
             "label" => "In pull request"
           }

    assert flows["design_and_accept"]["states"]["design_gate"]["spec"] ==
             %{"gate" => "design", "version" => 1}

    assert %{"kind" => "effect", "spec" => %{"field" => "integration", "gate" => "integrate"}} =
             flows["pull_request"]["states"]["integrating"]

    assert %{"flavor" => "rule", "purpose" => "flow", "rule" => %{"all" => [_, _, _]}} =
             Committed.gates()["integrate"]

    assert Map.keys(Committed.gates()) == [
             "accept_decision",
             "delivery_evidence",
             "design",
             "integrate",
             "review"
           ]
  end

  @tag :rela
  test "the pinned rela finds it valid in the Rela description, with the approved versions" do
    bin = Path.join(System.fetch_env!("ATLAS_RELA_BIN"), "rela")
    yaml = File.read!("../../rela/flows.yaml")

    assert {:ok, shown} =
             Rela.check(bin, yaml, resolved(), project: Path.expand("../../rela"))

    assert Enum.map(shown, &{String.to_atom(&1["name"]), &1["version"]}) ==
             Enum.flat_map(@versions, &elem(&1, 1))
  end
end
