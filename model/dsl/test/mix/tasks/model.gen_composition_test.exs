defmodule Mix.Tasks.Model.GenCompositionTest do
  # Sets the application's config and ATLAS_RELA_BIN, so not async.
  use ExUnit.Case

  @moduletag :tmp_dir

  @git ["-c", "user.name=test", "-c", "user.email=test@example.invalid"]

  setup %{tmp_dir: dir} do
    real = System.get_env("ATLAS_RELA_BIN")
    System.delete_env("ATLAS_RELA_BIN")
    rela = Path.join(dir, "rela")
    File.mkdir_p!(rela)
    File.write!(Path.join(rela, "data-entry.yaml"), "app:\n  name: Office\n")
    Application.put_env(:rela_dsl, :contract, RelaDSL.Office)
    Application.put_env(:rela_dsl, :rela_project, rela)
    Application.put_env(:rela_dsl, :root, dir)

    Application.put_env(:rela_dsl, :targets,
      atlas: Path.join(dir, "model/targets/atlas"),
      proof: Path.join(dir, "model/targets/proof")
    )

    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :rela_project, :root, :targets],
          do: Application.delete_env(:rela_dsl, key)

      if real,
        do: System.put_env("ATLAS_RELA_BIN", real),
        else: System.delete_env("ATLAS_RELA_BIN")

      Mix.shell(Mix.Shell.IO)
    end)

    %{rela: rela, digests: Path.join(dir, "model/targets/proof/digests.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.Model.Gen.run(args)

  defp git(dir, args) do
    {out, status} =
      System.cmd("git", ["-C", dir] ++ @git ++ args,
        stderr_to_stdout: true,
        env: [{"GIT_CONFIG_GLOBAL", "/dev/null"}, {"GIT_CONFIG_NOSYSTEM", "1"}]
      )

    assert status == 0, out
  end

  test "writes the Rela project and the proof; --check then passes", %{
    rela: rela,
    digests: digests
  } do
    gen()

    for path <-
          ~w(schema.yaml modules/post/schema.yaml compositions/office/bindings.yaml acl.yaml atlas.json flow-runtime.json) do
      assert File.read!(Path.join(rela, path)) ==
               File.read!(Path.join("test/golden/office", path)),
             path
    end

    assert "# Generated by atlas (mix model.gen) from " <> _ =
             File.read!(Path.join(rela, "flows.yaml"))

    assert %{"subflows" => %{"letter" => %{"prod" => _, "test" => _}}} =
             JSON.decode!(File.read!(digests))

    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "--check fails on a hand edit of a Rela input, and writing restores it", %{rela: rela} do
    gen()
    path = Path.join(rela, "modules/post/schema.yaml")
    File.write!(path, File.read!(path) <> "# edited\n")

    assert_raise Mix.Error, ~r/out of date.*modules\/post\/schema.yaml/, fn ->
      gen(["--check"])
    end

    gen()
    assert File.read!(path) == File.read!("test/golden/office/modules/post/schema.yaml")
  end

  test "a file the model no longer writes under modules/ or compositions/ is left over", %{
    rela: rela
  } do
    gen()
    stray = Path.join(rela, "modules/post/atlas.json")
    File.write!(stray, "{}\n")
    assert_raise Mix.Error, ~r/atlas.json \(left over\)/, fn -> gen(["--check"]) end
    gen()
    refute File.exists?(stray)
    assert File.exists?(Path.join(rela, "data-entry.yaml"))
  end

  test "--out writes only the project of --contract, with the project's data-entry.yaml", %{
    tmp_dir: dir
  } do
    out = Path.join(dir, "profile")
    gen(["--contract", "RelaDSL.Office", "--out", out])
    assert File.read!(Path.join(out, "data-entry.yaml")) == "app:\n  name: Office\n"
    assert File.read!(Path.join(out, "atlas.json")) == File.read!("test/golden/office/atlas.json")
    refute File.exists?(Path.join(dir, "model/targets/proof/digests.json"))
  end

  # The base is a repository of its own, outside the checkout.
  test "--base: a base without digests.json predates the proof; one with it is checked" do
    dir = Path.join(System.tmp_dir!(), "model-gen-base-#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    # git reads no configuration of the machine it runs on.
    for {k, v} <- [{"GIT_CONFIG_GLOBAL", "/dev/null"}, {"GIT_CONFIG_NOSYSTEM", "1"}] do
      previous = System.get_env(k)
      System.put_env(k, v)
      on_exit(fn -> if previous, do: System.put_env(k, previous), else: System.delete_env(k) end)
    end

    digests = Path.join(dir, "model/targets/proof/digests.json")
    Application.put_env(:rela_dsl, :root, dir)
    Application.put_env(:rela_dsl, :targets, proof: Path.dirname(digests))

    git(dir, ["init", "-q", "--template=", "-b", "base"])
    File.write!(Path.join(dir, "README"), "x\n")
    git(dir, ["add", "README"])
    git(dir, ["commit", "-qm", "before the proof"])
    gen(["--base", "base"])

    assert_received {:mix_shell, :info,
                     [
                       "the base base holds no model/targets/proof/digests.json yet; its history starts here"
                     ]}

    # The base recorded a history entry that the model no longer has.
    gen()
    base = JSON.decode!(File.read!(digests))
    gone = %{"digest" => String.duplicate("e", 64), "states" => ["write"]}
    base = update_in(base, ["subflows", "letter", "prod", "history"], &[gone | &1])

    File.write!(
      digests,
      RelaDSL.Header.put(
        ".json",
        "x.ex",
        RelaDSL.Description.Json.write(Map.delete(base, "_generated"))
      )
    )

    git(dir, ["add", "model/targets/proof/digests.json"])
    git(dir, ["commit", "-qm", "the proof"])
    gen()

    assert_raise Mix.Error,
                 ~r/against the base base:\n  letter \(prod\): history entry eeeeeeee… was removed/,
                 fn ->
                   gen(["--check", "--base", "base"])
                 end

    assert_raise Mix.Error, ~r/--base nowhere: /, fn -> gen(["--check", "--base", "nowhere"]) end
  end
end
