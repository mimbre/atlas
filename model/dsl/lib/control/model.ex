defmodule RelaDSL.Control.Model do
  @moduledoc """
  What a composition compiles for the component that serves pages, as callbacks of the
  composition's root module (generated by `RelaDSL.Composition`):

    * `shell(settings)`: the title and tabs of the native shell (`shell`), with the tabs
      the environment's settings add (`"tabs"`); nil without `shell`;
    * `start_page/0`: what a client opens on (`start_page`): `assigned` (what is assigned
      to it), `open` (open work, for everyone) and the start page's `actions`;
    * `kinds/0`: every kind, sorted by name, with its names, its id, its fields in the
      order pages show them, the relations that start at it, and what its pages show
      besides (counts, progress, lateness, the fields a flow keeps to itself);
    * `form(kind, mode)`: what a create (`:create`) or change (`:edit`) form asks, its
      defaults, the field an id is made from and the value that decides (`authority`);
    * `key(kind, values)`: the key of a new fact whose id is made from a field;
    * `actions(kind, fact, viewer)`: the operations a kind offers by hand (`fact` nil),
      or those a fact's page offers, with the actions the model adds (`action`);
    * `todo(kind, fact, parts, viewer)`: what the fact's owner is to do in the state its
      run is in, and the answers they can give; nil for anyone else;
    * `answer(kind, name, item, viewer)`: the change an owner's answer writes.

  Every name is resolved, every default applied and every list ordered when the model
  compiles; nothing is read from a file. The callbacks that depend on a fact evaluate
  the compiled rules with `RelaDSL.Control.Rules`.
  """

  @doc false
  def body(schema, extension, flow_runtime) do
    d = merge(schema, extension)
    presenters = RelaDSL.Presentation.presenters(d, flow_runtime)
    kinds = kinds(d, presenters)
    flows = flows(d, presenters)

    quote do
      @doc "The native shell: its title and tabs, with the tabs `settings` add; nil without one."
      def shell(settings),
        do: RelaDSL.Control.Rules.shell(unquote(Macro.escape(d["shell"])), settings)

      @doc "What a client opens on: what is assigned to it, open work and the start actions."
      def start_page, do: unquote(Macro.escape(start_page(d)))

      @doc "Every kind, as pages show it, sorted by name."
      def kinds, do: unquote(Macro.escape(kinds))

      @doc "What a create (`:create`) or change (`:edit`) form of `kind` asks; nil for no kind."
      unquote_splicing(
        for {name, spec} <- Enum.sort(d["entities"] || %{}), mode <- [:create, :edit] do
          quote do
            def form(unquote(name), unquote(mode)),
              do: unquote(Macro.escape(form(d, name, spec, mode)))
          end
        end
      )

      def form(_kind, _mode), do: nil

      @doc "The key of a new fact of `kind` whose id is made from a field of `values`."
      unquote_splicing(
        for {name, spec} <- Enum.sort(d["entities"] || %{}),
            %{"from" => from} = rule when is_binary(from) <- [get_in(spec, ["create", "id"])] do
          quote do
            def key(unquote(name), values),
              do: RelaDSL.Control.Rules.key(unquote(Macro.escape(rule)), values)
          end
        end
      )

      def key(_kind, _values), do: {:error, "the id is not made from a field"}

      @doc "What a kind offers by hand (`fact` nil), or what a fact's page offers."
      unquote_splicing(
        for {name, spec} <- Enum.sort(d["entities"] || %{}) do
          quote do
            def actions(unquote(name), fact, viewer),
              do:
                RelaDSL.Control.Rules.actions(
                  unquote(Macro.escape(action_rule(d, name, spec))),
                  fact,
                  viewer
                )
          end
        end
      )

      def actions(_kind, _fact, _viewer), do: []

      @doc "What the owner of `fact` is to do, for a viewer that is its owner; else nil."
      unquote_splicing(
        for {name, flow} <- Enum.sort(flows) do
          quote do
            def todo(unquote(name), fact, parts, viewer),
              do: RelaDSL.Control.Rules.todo(unquote(Macro.escape(flow)), fact, parts, viewer)
          end
        end
      )

      def todo(_kind, _fact, _parts, _viewer), do: nil

      @doc "The change the owner's answer `name` writes on the item, or why it is refused."
      unquote_splicing(
        for {name, flow} <- Enum.sort(flows) do
          quote do
            def answer(unquote(name), answer, item, viewer),
              do: RelaDSL.Control.Rules.answer(unquote(Macro.escape(flow)), answer, item, viewer)
          end
        end
      )

      def answer(_kind, _answer, _item, _viewer),
        do: RelaDSL.Control.Rules.answer(nil, nil, nil, nil)
    end
  end

  # -- The description pages are made from ----------------------------------------------

  # The schema with Atlas's additions merged in, key by key, as rela and Facts serve it:
  # a kind without a primary field of its own gets the one rela gives it (`primary/1`), a
  # kind's id prefixes are a list, and a property of a type with values carries them and
  # their labels. Atlas's own `primary` (an addition) wins over rela's.
  @doc false
  def merge(schema, extension) do
    schema =
      Map.update(schema, "entities", %{}, fn entities ->
        Map.new(entities, fn {kind, spec} ->
          {kind, if(spec["primary"], do: spec, else: put_primary(spec))}
        end)
      end)

    d = deep_merge(schema, Map.drop(extension, ["_about"]))
    types = d["types"] || %{}

    entities =
      Map.new(d["entities"] || %{}, fn {kind, spec} ->
        properties =
          Map.new(spec["properties"] || %{}, fn {name, prop} ->
            type = types[prop["type"]] || %{}

            prop =
              if is_list(type["values"]),
                do:
                  prop
                  |> Map.put_new("values", type["values"])
                  |> Map.put_new("labels", type["labels"] || %{}),
                else: prop

            {name, prop}
          end)

        spec = Map.put(spec, "properties", properties)

        spec =
          if is_binary(spec["id_prefix"]) and not Map.has_key?(spec, "id_prefixes"),
            do: Map.put(spec, "id_prefixes", [spec["id_prefix"]]),
            else: spec

        {kind, spec}
      end)

    Map.put(d, "entities", entities)
  end

  # The primary field rela 26.11 serves for a kind that declares none: among its required
  # string fields, `title`, else `name`, else the first by name; none without one.
  defp put_primary(spec) do
    required =
      for {name, %{"type" => "string", "required" => true}} <- spec["properties"] || %{},
          do: name

    case Enum.find(["title", "name"], &(&1 in required)) || List.first(Enum.sort(required)) do
      nil -> spec
      primary -> Map.put(spec, "primary", primary)
    end
  end

  defp deep_merge(left, right),
    do:
      Map.merge(left, right, fn _key, l, r ->
        if is_map(l) and is_map(r), do: deep_merge(l, r), else: r
      end)

  # -- Kinds ------------------------------------------------------------------------------

  @doc false
  def kinds(d, presenters \\ []) do
    relations = d["relations"] || %{}

    children =
      for {_name, %{"from" => from} = spec} <- relations, parent?(spec), kind <- from, do: kind

    for {kind, spec} <- Enum.sort(d["entities"] || %{}) do
      rule = create_rule(spec)

      %{
        name: kind,
        label: singular(spec, kind),
        plural: plural(spec, kind),
        about: spec["description"],
        top: kind not in children and spec["top"] != false,
        newest_first: spec["order"] == "newest",
        primary: spec["primary"] || id_property(spec),
        id: %{
          prefix: rule.prefix,
          digits: rule.digits,
          first: rule.first,
          from: rule.from,
          template: get_in(spec, ["create", "id", "template"]),
          prefixes:
            Enum.uniq(
              for p <- [rule.prefix | spec["id_prefixes"] || []], p not in [nil, ""], do: p
            )
        },
        fields: fields(d, kind, spec),
        relations:
          for(
            {name, rel} <- Enum.sort(relations),
            kind in (rel["from"] || []),
            do: relation(name, rel)
          ),
        counts:
          for(
            %{"relation" => relation, "text" => text} <- spec["counts"] || [],
            kind in (get_in(relations, [relation, "to"]) || []),
            from <- get_in(relations, [relation, "from"]) || [],
            do: %{relation: relation, from: from, text: text}
          ),
        progress:
          if(is_map(spec["progress"]),
            do: %{hidden: [spec["progress"]["own"]]}
          ),
        shows_progress: is_map(spec["progress"]) or completion_rules(spec) != [],
        done_label: get_in(d, ["progress", "done_label"]),
        late:
          case spec["late"] do
            %{"after" => after_field} = late -> %{after: after_field, label: late["label"]}
            _ -> nil
          end,
        start:
          case spec["start"] do
            %{"key" => key, "label" => label} -> %{key: key, label: label}
            _ -> nil
          end,
        agent: spec["agent"],
        delete_error: if(is_binary(spec["delete_error"]), do: spec["delete_error"]),
        hidden: state_fields(presenters, kind),
        presented: Enum.any?(presenters, &(&1["kind"] == kind))
      }
    end
  end

  # The fields in the order pages show them: the primary (or the one the id is made from)
  # first, then choices, then flags, then the rest, so long text ends up last.
  defp fields(d, kind, spec) do
    primary = spec["primary"] || id_property(spec)
    types = d["types"] || %{}

    (spec["properties"] || %{})
    |> Enum.sort_by(fn {name, prop} ->
      rank =
        cond do
          name == primary -> 0
          is_list(prop["values"]) -> 1
          prop["type"] == "boolean" -> 2
          true -> 3
        end

      {rank, name}
    end)
    |> Enum.map(fn {name, prop} ->
      %{
        name: name,
        label: prop["label"] || humanize(name),
        type: prop["type"],
        values: if(is_list(prop["values"]), do: prop["values"]),
        labels: Map.merge(get_in(types, [prop["type"], "labels"]) || %{}, prop["labels"] || %{}),
        required: prop["required"] == true,
        hint: prop["description"],
        settable: not Map.has_key?(prop, "set_by"),
        set_by: prop["set_by"],
        multiline: prop["multiline"] == true,
        url: prop["format"] == "url" or get_in(types, [prop["type"], "format"]) == "url",
        cause:
          case prop["cause"] do
            cause when cause in [nil, false] -> nil
            cause when is_binary(cause) -> cause
            _ -> plural(spec, kind)
          end
      }
    end)
  end

  defp relation(name, rel) do
    actions = rel["actions"] || %{}
    pair = fn op -> with %{"label" => l, "key" => k} <- actions[op], do: %{label: l, key: k} end

    %{
      name: name,
      label: rel["label"] || name,
      description: rel["description"],
      from: rel["from"] || [],
      to: rel["to"] || [],
      one: rel["max_outgoing"] == 1,
      parent: parent?(rel),
      inverse_label: get_in(rel, ["inverse", "label"]),
      component: if(is_map(rel["component"]), do: rel["component"]),
      set_by: if(Map.has_key?(rel, "set_by"), do: List.wrap(rel["set_by"])),
      only_target:
        case rel["only_target"] do
          %{} = only -> %{error: only["error"], also: only["also"] || []}
          _ -> nil
        end,
      set: if(is_map(actions), do: pair.("set")),
      remove: if(is_map(actions), do: pair.("remove")),
      change:
        case is_map(actions) && actions["change"] do
          %{} = change ->
            %{
              label: change["label"],
              key: change["key"],
              with: List.wrap(change["with"]),
              cause: change["cause"]
            }

          _ ->
            nil
        end,
      requires_completed_children:
        if(is_binary(rel["requires_completed_children"]),
          do: rel["requires_completed_children"]
        ),
      closes_parent: if(is_binary(rel["closes_parent"]), do: rel["closes_parent"]),
      limit:
        case rel["limit"] do
          %{} = limit ->
            %{
              max: limit["max"],
              field: limit["field"],
              values: limit["values"] || [],
              error: limit["error"]
            }

          _ ->
            nil
        end,
      add: rel["add"] != false
    }
  end

  # A fact belongs under the one it points at through a parent relation; at most one.
  defp parent?(spec), do: spec["parent"] == true and spec["max_outgoing"] == 1

  defp completion_rules(spec) do
    case spec["completion"] do
      rules when is_list(rules) -> rules
      %{} = rule -> [rule]
      _ -> []
    end
  end

  # The fields a presenter keeps on `kind` to itself: the state is shown in What to do;
  # bookkeeping (a deferred handover) stays hidden.
  defp state_fields(presenters, kind) do
    for p <- presenters,
        p["kind"] == kind,
        field <- [p["state_field"], p["handover_field"]],
        is_binary(field),
        uniq: true,
        do: field
  end

  # -- The start page ---------------------------------------------------------------------

  defp start_page(d) do
    assigned =
      case get_in(d, ["start", "assigned"]) do
        %{"relation" => relation} = rule when is_binary(relation) ->
          %{relation: relation, title: rule["title"], empty: rule["empty"], count: rule["count"]}

        _ ->
          nil
      end

    open =
      case {get_in(d, ["start", "open"]), assigned} do
        {%{} = rule, %{}} ->
          %{title: rule["title"], empty: rule["empty"]}

        _ ->
          nil
      end

    %{
      assigned: assigned,
      open: open,
      actions:
        for(
          {kind, %{"start" => %{"key" => key, "label" => label}}} <-
            Enum.sort(d["entities"] || %{}),
          do: %{kind: kind, key: key, label: label}
        )
    }
  end

  # -- Forms ------------------------------------------------------------------------------

  defp form(_d, _kind, spec, :create) do
    rule = create_rule(spec)
    %{ask: rule.ask, defaults: rule.defaults, made_from: rule.from, decides: nil}
  end

  defp form(_d, _kind, spec, :edit) do
    made_from = id_property(spec)
    primary = spec["primary"] || made_from

    ask =
      for {name, prop} <- ordered(spec, primary),
          not Map.has_key?(prop, "set_by"),
          name != made_from,
          do: name

    decides =
      case spec["authority"] do
        %{"by" => relation, "writes" => %{} = writes} ->
          %{
            relation: relation,
            writes:
              Map.new(writes, fn {field, allowed} ->
                {field, Enum.map(List.wrap(allowed), &to_string/1)}
              end)
          }

        _ ->
          nil
      end

    %{ask: ask, defaults: %{}, made_from: made_from, decides: decides}
  end

  defp ordered(spec, primary) do
    Enum.sort_by(spec["properties"] || %{}, fn {name, prop} ->
      rank =
        cond do
          name == primary -> 0
          is_list(prop["values"]) -> 1
          prop["type"] == "boolean" -> 2
          true -> 3
        end

      {rank, name}
    end)
  end

  # How a fact of a kind is created: what a create asks (by default every field a user
  # may set), its id (a prefix and the next number, or made from a field) and defaults.
  defp create_rule(spec) do
    rule = spec["create"] || %{}
    prefix = List.first(spec["id_prefixes"] || List.wrap(spec["id_prefix"])) || ""
    primary = spec["primary"] || id_property(spec)

    %{
      ask:
        rule["ask"] ||
          for({name, prop} <- ordered(spec, primary), not Map.has_key?(prop, "set_by"), do: name),
      prefix: get_in(rule, ["id", "prefix"]) || prefix,
      digits: get_in(rule, ["id", "digits"]) || 2,
      first: get_in(rule, ["id", "first"]) || 1,
      from: get_in(rule, ["id", "from"]),
      defaults: rule["defaults"] || %{}
    }
  end

  defp id_property(spec), do: get_in(spec, ["create", "id", "from"])

  # -- Actions ----------------------------------------------------------------------------

  # A kind the agent alone writes (`by_hand: false`) offers no operation; `"update"` only a
  # change (a kind made and deleted with another fact); one never deleted (`delete_error`)
  # no delete. A fact can be changed when a user may set one of its fields, or move it.
  defp action_rule(d, kind, spec) do
    by_hand =
      for op <- [:create, :update, :delete],
          by_hand?(spec["by_hand"], op),
          not (op == :delete and is_binary(spec["delete_error"])),
          do: op

    parents =
      for {_name, rel} <- d["relations"] || %{},
          parent?(rel),
          kind in (rel["from"] || []),
          do: rel

    made_from = id_property(spec)

    changeable =
      parents != [] or
        Enum.any?(spec["properties"] || %{}, fn {name, prop} ->
          not Map.has_key?(prop, "set_by") and name != made_from
        end)

    %{
      by_hand: by_hand,
      changeable: changeable,
      described:
        for(
          %{"key" => key, "label" => label, "to" => to} = described <- spec["actions"] || [],
          do: %{key: key, label: label, to: to, when: described["when"] || %{}}
        )
    }
  end

  defp by_hand?(false, _op), do: false
  defp by_hand?("update", op), do: op == :update
  defp by_hand?(_by_hand, _op), do: true

  # -- What the owner is to do ------------------------------------------------------------

  # Per kind whose work is presented (the first presenter of it): where its presentation
  # is on (the fact, or the one component its `on` relation points at, whose Facts read
  # carries the presentation), and the words of What to do. What each state shows, Facts'
  # presentation says (`RelaDSL.Presentation`).
  defp flows(d, presenters) do
    words = d["todo"] || %{}

    for p <- Enum.reverse(presenters), into: %{} do
      {p["subject"],
       %{
         on: p["on"],
         on_kind: if(p["on"], do: p["kind"]),
         owner_relation: p["owner_relation"],
         words: %{
           title: to_text(words["title"]),
           why: to_text(words["why"]),
           instructions: to_text(words["instructions"]),
           answers: to_text(words["answers"]),
           reopened: to_text(words["reopened"])
         }
       }}
    end
  end

  # -- Names ------------------------------------------------------------------------------

  defp singular(spec, kind), do: spec["label"] || humanize(kind)
  defp plural(spec, kind), do: humanize(spec["plural"] || kind <> "s")
  defp humanize(name), do: name |> String.replace("_", " ") |> String.capitalize()
  defp to_text(nil), do: ""
  defp to_text(v) when is_binary(v), do: v
  defp to_text(v), do: to_string(v)
end
