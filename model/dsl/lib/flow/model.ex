defmodule RelaDSL.Flow.Model do
  @moduledoc """
  What a composition compiles for the components that run it, as callbacks of the
  composition's root module (generated by `RelaDSL.Composition`):

    * `subflows(environment)`: the module of each subflow it runs, compiled with that
      environment's limits (`RelaDSL.Flow.Subflow`), as `<Root>.Subflows.<Name>.<Env>`;
      an environment it does not declare raises;
    * `legacy/0`: the module of each legacy flow (`RelaDSL.Flow.Legacy`), as
      `<Root>.Legacy.<Name>`, sorted by name;
    * `runs/0`: where runs are kept (`kind`, `fields`, `writer`, `inputs`), nil when no
      concept declares `flow_runtime`;
    * `selection(subflow)`: how the runs of a subflow are selected, imported and
      projected (`select`), with its approved `migrations`; nil when it is not selected;
    * `migrations/0`: every approved migration, with its `subflow`;
    * `actors/0`: the configured actors the model needs;
    * `relations/0`: every relation, by name, as the store describes it with the model's
      additions (`parent`, `component`, ...): what a runner walks from a fact to the
      facts above and under it;
    * `gates/0`: every gate, by name, as data;
    * `ids/0`: how the key of a fact of each kind is made, by kind: `prefix` and
      `digits` (the next number), and every `prefixes` its keys start with.

  All of it is data the macros built when the model compiled; nothing is read from a
  file.
  """

  alias RelaDSL.Description.Plain
  alias RelaDSL.Flow.{Legacy, Subflow}

  @doc false
  def body(root, opts, flows, gates, environments, schema, extension, flow_runtime) do
    subflow_behaviour = opts[:subflow_behaviour]
    legacy_behaviour = opts[:legacy_behaviour]
    file = to_string(root)

    by_env =
      for env <- environments do
        definitions = Subflow.definitions(flows, gates, env)

        modules =
          for name <- Enum.sort(Map.keys(definitions)) do
            module = Module.concat([root, "Subflows", Macro.camelize(name), camel(env)])
            {module, Subflow.body(name, definitions[name], subflow_behaviour, file)}
          end

        {env, modules}
      end

    legacy =
      for {name, flow} <- Enum.sort(extension["flows"] || %{}), is_map(flow) do
        {Module.concat([root, "Legacy", Macro.camelize(name)]),
         Legacy.body(name, flow, legacy_behaviour)}
      end

    runtime = if flow_runtime, do: Plain.unorder(flow_runtime)["flow_runtime"]
    selection = (runtime && runtime["selection"]) || %{}

    runs =
      runtime && Map.take(runtime, ["kind", "fields", "writer", "inputs"])

    migrations =
      for {name, s} <- Enum.sort(selection),
          m <- s["migrations"] || [],
          do: Map.put(m, "subflow", name)

    modules =
      for {module, body} <- Enum.flat_map(by_env, &elem(&1, 1)) ++ legacy do
        quote do
          defmodule unquote(module) do
            @moduledoc false
            unquote(body)
          end
        end
      end

    described = RelaDSL.Facts.Model.described(RelaDSL.Facts.Served.of(schema), extension, nil)

    ids =
      Map.new(described["entities"] || %{}, fn {kind, spec} ->
        prefix = get_in(spec, ["create", "id", "prefix"]) || spec["id_prefix"]

        {kind,
         %{
           "prefix" => prefix,
           "digits" => get_in(spec, ["create", "id", "digits"]) || 2,
           "prefixes" => [prefix | spec["id_prefixes"] || []]
         }}
      end)

    quote do
      unquote_splicing(modules)

      @doc "The module of each subflow the model runs, for `environment`."
      unquote_splicing(
        for {env, list} <- by_env do
          quote(do: def(subflows(unquote(env)), do: unquote(Enum.map(list, &elem(&1, 0)))))
        end
      )

      def subflows(environment),
        do:
          raise(
            ArgumentError,
            "the model declares no environment #{inspect(environment)} " <>
              "(environments: #{unquote(inspect(environments))})"
          )

      @doc "The module of each legacy flow, sorted by name."
      def legacy, do: unquote(Enum.map(legacy, &elem(&1, 0)))

      @doc "Where the runs are kept, or nil."
      def runs, do: unquote(Macro.escape(runs))

      @doc "How a subflow's runs are selected, or nil when they are not."
      unquote_splicing(
        for {name, s} <- Enum.sort(selection) do
          quote(do: def(selection(unquote(name)), do: unquote(Macro.escape(s))))
        end
      )

      def selection(_subflow), do: nil

      @doc "Every approved run migration, with its subflow."
      def migrations, do: unquote(Macro.escape(migrations))

      @doc "The configured actors the model needs."
      def actors, do: []

      @doc "Every relation, by name, with the model's additions."
      def relations, do: unquote(Macro.escape(described["relations"] || %{}))

      @doc "Every gate, by name, as data."
      def gates, do: unquote(Macro.escape(RelaDSL.Atlas.gate_data(gates)))

      @doc "How the key of a fact of each kind is made: `prefix`, `digits`, `prefixes`."
      def ids, do: unquote(Macro.escape(ids))
    end
  end

  defp camel(env), do: env |> to_string() |> Macro.camelize()
end
