defmodule RelaDSL.Facts.Model do
  @moduledoc """
  What a composition compiles for the store at Facts' place, as callbacks of the
  composition's root module (generated by `RelaDSL.Composition`):

    * `rela_schema/0`: the schema rela must serve (`entities`, `relations`, `types`, as
      the pinned rela serves them, `RelaDSL.Facts.Served`); a store compares it with
      what rela serves when it starts;
    * `check(kind, change, actor, lookup)`: whether a change may be stored, `:ok` or
      `{:refuse, reasons}` (`RelaDSL.Facts.Writes`);
    * `with_change(kind, change, lookup)`: the changes the write makes, in order
      (components, the change itself, what it replaces; `RelaDSL.Facts.Writes`);
    * `derived(kind, facts, lookup)`: what is worked out for each fact on a read
      (completion, progress, review, late; `RelaDSL.Facts.Derived`);
    * `run_mapping/0`: where runs and their inputs are kept, who writes them, and what
      each selected subflow takes choices on; nil without `flow_runtime`;
    * `presentation/0`: who presents the work on each kind of fact: the presenters
      (`RelaDSL.Presentation`), from which Facts serves a fact's presentation;
    * `connector(kind)`: the outside system a kind's facts are copied from, or nil:
      `%{"system", "address", "fields", "until", "names"}`, where `names` (when given)
      carries the `kind` its `relation` starts at and that kind's id `prefix` (nil when
      it has none).

  A `change` is `%{"op" => "create" | "change" | "delete", "key", "values", "links" =>
  %{relation => [key]}, "by"}`; an `actor` `%{"by", "sender"}`. `lookup` is the store's
  reader, so no rule calls a service:

    * `"current"`: `fn -> nil | %{"values", "links"} end`, the fact as it is stored
      before the write;
    * `"fact"`: `fn kind, key -> nil | fact end`;
    * `"list"`: `fn kind -> {:ok, [fact]} | {:error, reason} end`;
    * `"incoming"`: `fn kind, key, relation -> [key] end`, what points at a fact;
    * `"fingerprint"`: `fn fact, spec -> digest end`, a subject's fingerprint;
    * for `derived`, what its rules read, asked as precisely as they read it, so a store
      can say what a read depended on: `"linked"`, `fn kind, relation, keys -> {:ok,
      [fact]} | {:error, reason} end` (the facts of `kind` that point at one of `keys`
      through `relation`), and `"facts"`, `fn kind, keys -> {:ok, [fact]} | {:error,
      reason} end` (those of `kind` with one of `keys`);
    * `"now"` (optional, for `derived`): the time lateness is worked out at.

  A `fact` is as rela gives it: `%{key, properties, links}`.

  The rules are the model's description compiled in: rela's schema as served, with the
  model's additions (`atlas.json`) over it and the run mapping's reviews and flags;
  nothing is read from a file.
  """

  alias RelaDSL.Facts.Served

  @doc false
  def body(schema, extension, flow_runtime, presentations \\ %{}) do
    served = Served.of(schema)
    d = described(served, extension, flow_runtime)
    presenters = RelaDSL.Presentation.presenters(d, flow_runtime, presentations)

    connectors =
      for {kind, %{"connector" => %{} = rule}} <- Enum.sort(d["entities"] || %{}),
          do: {kind, connector(d, rule)}

    quote do
      @doc "The schema rela must serve: `entities`, `relations` and `types`, as rela serves them."
      def rela_schema, do: unquote(Macro.escape(served))

      @doc "Whether a change of a fact of `kind` may be stored: `:ok` or `{:refuse, reasons}`."
      def check(kind, change, actor, lookup),
        do: RelaDSL.Facts.Writes.check(__facts__(), kind, change, actor, lookup)

      @doc "The changes one write of a fact of `kind` makes, in order."
      def with_change(kind, change, lookup),
        do: RelaDSL.Facts.Writes.with_change(__facts__(), kind, change, lookup)

      @doc "What is worked out for each of `facts` of `kind` on a read."
      def derived(kind, facts, lookup),
        do: RelaDSL.Facts.Derived.of(__facts__(), kind, facts, lookup)

      @doc "Where runs and their inputs are kept and who writes them; nil without one."
      def run_mapping, do: unquote(Macro.escape(run_mapping(d["flow_runtime"], d["relations"])))

      @doc "Who presents the work on each kind of fact (`RelaDSL.Presentation`)."
      def presentation, do: unquote(Macro.escape(presenters))

      @doc "The outside system the facts of `kind` are copied from, or nil."
      unquote_splicing(
        for {kind, rule} <- connectors do
          quote(do: def(connector(unquote(kind)), do: unquote(Macro.escape(rule))))
        end
      )

      def connector(_kind), do: nil

      defp __facts__, do: unquote(Macro.escape(d))
    end
  end

  @doc """
  The description the rules read: the served schema with the model's additions merged in,
  key by key (an addition wins), the run mapping's reviews added to their relations and
  the run mapping itself (`flow_runtime`) beside them.
  """
  def described(served, extension, flow_runtime) do
    d = merge(served, Map.drop(extension || %{}, ["_about"]))

    case flow_runtime do
      %{"flow_runtime" => config} ->
        d =
          Enum.reduce(config["reviews"] || %{}, d, fn {relation, rules}, d ->
            update_in(d, ["relations", relation, "review"], &(List.wrap(&1) ++ rules))
          end)

        Map.put(d, "flow_runtime", config)

      _ ->
        d
    end
  end

  defp merge(left, right) do
    Map.merge(left, right, fn _key, l, r ->
      if is_map(l) and is_map(r), do: merge(l, r), else: r
    end)
  end

  defp run_mapping(nil, _relations), do: nil

  defp run_mapping(config, relations) do
    # Rela's public schema has no Atlas component rules. Carry only the component
    # definitions needed by choice authorization in the compiled Facts contract.
    components =
      Map.new(
        for {name, %{"component" => %{}} = spec} <- relations || %{},
            do: {name, Map.take(spec, ~w(from to component))}
      )

    config =
      if is_map(config["inputs"]),
        do: put_in(config, ["inputs", "components"], components),
        else: config

    config
    |> Map.take(["kind", "fields", "writer", "inputs"])
    |> Map.put(
      "selection",
      Map.new(config["selection"] || %{}, fn {name, s} ->
        {name, Map.take(s, ["subject", "choices", "choice_states"])}
      end)
    )
  end

  defp connector(d, rule) do
    case rule["names"] do
      %{"relation" => relation} = names ->
        target =
          case get_in(d, ["relations", relation, "from"]) do
            [target] -> target
            _ -> nil
          end

        prefix =
          case target && get_in(d, ["entities", target, "create", "id", "prefix"]) do
            prefix when is_binary(prefix) and prefix != "" -> prefix
            _ -> nil
          end

        Map.put(rule, "names", Map.merge(names, %{"kind" => target, "prefix" => prefix}))

      _ ->
        rule
    end
  end
end
