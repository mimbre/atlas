defmodule RelaDSL.Runtime.Model do
  @moduledoc """
  What a composition compiles for the component that runs turns, as callbacks of the
  composition's root module (generated by `RelaDSL.Composition`):

    * `turn/0`: the names of the turn's kind and fields (`runtime turn:`), with
      `on_kinds` (the kinds its `on` relation leads to) and `items` (the facts a turn
      works on: each legacy flow with an owner relation gives the kinds it writes on,
      with `owner_relation`, `state_field` and `handover_field`, in the flows' order and
      each once); nil without `runtime`;
    * `agent/0`: `kind` (the one kind the turn's `by` leads to, or nil) and
      `cannot_run` (`runtime agent:`); nil without `runtime`;
    * `guidance/0`: the guidance records (`guidance`), or nil;
    * `read_first(fact, lookup)`: what a worker reads before it acts on `fact`
      (`read_first`, see `RelaDSL.Runtime.ReadFirst`); nil without one.

  All of it is data the macros built when the model compiled; nothing is read from a
  file.
  """

  @doc false
  def body(schema, extension) do
    relations = schema["relations"] || %{}
    runtime = extension["runtime"] || %{}
    names = runtime["turn"]

    turn =
      names &&
        Map.merge(names, %{
          "on_kinds" => to(relations, names["on"]),
          "items" => items(relations, extension["flows"] || %{})
        })

    agent =
      runtime["agent"] && names &&
        %{
          "kind" =>
            case to(relations, names["by"]) do
              [kind] -> kind
              _ -> nil
            end,
          "cannot_run" => runtime["agent"]["cannot_run"]
        }

    rule = read_first(schema, extension)

    quote do
      @doc "The turn's kind and fields, and the facts a turn works on; nil when it runs none."
      def turn, do: unquote(Macro.escape(turn))

      @doc "The agent a turn is by: its kind and the field that says it cannot run; or nil."
      def agent, do: unquote(Macro.escape(agent))

      @doc "The durable guidance records, by role; nil when the model keeps none."
      def guidance, do: unquote(Macro.escape(extension["guidance"]))

      @doc "What a worker reads before it acts on `fact`, as text; nil when nothing applies."
      unquote(
        if rule do
          quote do
            def read_first(fact, lookup),
              do: RelaDSL.Runtime.ReadFirst.text(unquote(Macro.escape(rule)), fact, lookup)
          end
        else
          quote(do: def(read_first(_fact, _lookup), do: nil))
        end
      )
    end
  end

  defp to(relations, name), do: (is_binary(name) && relations[name]["to"]) || []

  # The facts flows write on, owned through their owner relation: `on`'s one kind, or
  # their kinds.
  defp items(relations, flows) do
    for {_name, %{"owner_relation" => relation} = flow} <- Enum.sort(flows),
        is_binary(relation),
        kind <-
          (case to(relations, flow["on"]) do
             [to] -> [to]
             _ -> flow["kinds"] || []
           end),
        uniq: true,
        do: %{
          "kind" => kind,
          "owner_relation" => relation,
          "state_field" => flow["state_field"],
          "handover_field" => flow["handover_field"]
        }
  end

  # The rule with every name it shows resolved: the anchors' kind, its primary field,
  # the labels of the relations and of the tags' values.
  defp read_first(schema, extension) do
    with %{"through" => through} = spec <- extension["read_first"],
         [anchor] <- to(schema["relations"] || %{}, through) do
      relations = schema["relations"] || %{}
      properties = get_in(schema, ["entities", anchor, "properties"]) || %{}

      labels = fn name ->
        p = properties[name] || %{}
        p["labels"] || get_in(schema, ["types", p["type"], "labels"]) || %{}
      end

      %{
        title: spec["title"],
        through: through,
        through_label: relations[through]["label"] || through,
        then: spec["then"],
        then_label: (is_binary(spec["then"]) && relations[spec["then"]]["label"]) || spec["then"],
        anchor: anchor,
        primary:
          get_in(extension, ["entities", anchor, "primary"]) ||
            get_in(schema, ["entities", anchor, "primary"]),
        standing:
          for(
            group <- List.wrap(spec["standing"]),
            is_map(group),
            do: %{title: group["title"], first: group["first"] == true, when: group["when"]}
          ),
        tags: for(name <- spec["tags"] || [], do: {name, labels.(name)}),
        text: spec["text"]
      }
    else
      _ -> nil
    end
  end
end
