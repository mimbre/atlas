defmodule AtlasFlowGenerator.HeaderTest do
  use ExUnit.Case, async: true

  alias AtlasFlowGenerator.Header

  for ext <- [".yaml", ".md"] do
    test "a #{ext} file with the header is generated, whatever its source" do
      body = Header.put(unquote(ext), "lib/letter.ex", "body\n")
      assert String.ends_with?(body, "\nbody\n")
      assert body =~ "mix atlas.flow.gen"
      assert body =~ "lib/letter.ex"
      assert Header.generated?(unquote(ext), body)
    end
  end

  test "the YAML header is a comment and the Markdown header an HTML comment" do
    assert "# Generated by atlas" <> _ = Header.put(".yaml", "x.ex", "")
    assert "<!-- Generated by atlas" <> rest = Header.put(".md", "x.ex", "")
    assert rest =~ ~r/ -->\n$/
  end

  test "the JSON header is the object's first key, so the file stays JSON" do
    body = Header.put(".json", "lib/letter.ex", ~s({\n  "a": 1\n}\n))

    assert "{\n  \"_generated\": \"Generated by atlas (mix atlas.flow.gen) from lib/letter.ex." <>
             _ = body

    assert %{"_generated" => _, "a" => 1} = JSON.decode!(body)
    assert Header.generated?(".json", body)
    refute Header.generated?(".json", ~s({\n  "_generated": "mine",\n  "a": 1\n}\n))
    assert_raise ArgumentError, fn -> Header.put(".json", "x.ex", "{}\n") end
  end

  test "a hand-written file that only mentions the marker is not generated" do
    refute Header.generated?(".yaml", "flows:\n# Generated by atlas, they say\n")
    refute Header.generated?(".yaml", "# Generated by atlas (mix atlas.flow.gen) from\n")

    refute Header.generated?(
             ".md",
             "# Generated by atlas (mix atlas.flow.gen) from x. Do not edit: change the contract and regenerate.\n"
           )

    refute Header.generated?(".json", Header.put(".yaml", "x.ex", ""))
  end
end
