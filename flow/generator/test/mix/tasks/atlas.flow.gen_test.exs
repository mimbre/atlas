defmodule Mix.Tasks.Atlas.Flow.GenTest do
  # Sets the application's config and ATLAS_RELA_BIN, so not async.
  use ExUnit.Case

  @moduletag :tmp_dir

  setup %{tmp_dir: dir} do
    real = System.get_env("ATLAS_RELA_BIN")
    System.delete_env("ATLAS_RELA_BIN")
    Application.put_env(:atlas_flow_generator, :contract, AtlasFlowGenerator.Example)
    Application.put_env(:atlas_flow_generator, :gates, AtlasFlowGenerator.Example.Gates)

    Application.put_env(:atlas_flow_generator, :targets,
      rela: Path.join(dir, "rela"),
      atlas: Path.join(dir, "atlas"),
      diagrams: Path.join(dir, "diagrams")
    )

    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :gates, :targets],
          do: Application.delete_env(:atlas_flow_generator, key)

      if real,
        do: System.put_env("ATLAS_RELA_BIN", real),
        else: System.delete_env("ATLAS_RELA_BIN")

      Mix.shell(Mix.Shell.IO)
    end)

    %{
      real: real,
      yaml: Path.join(dir, "rela/flows.yaml"),
      json: Path.join(dir, "atlas/flows.json"),
      diagram: Path.join(dir, "diagrams/letter.md")
    }
  end

  defp gen(args \\ []), do: Mix.Tasks.Atlas.Flow.Gen.run(args)

  # A stand-in for rela that says it is 26.11.2 and refuses every flows.yaml.
  defp refusing_rela(dir, version \\ "rela version 26.11.2") do
    bin = Path.join(dir, "bin")
    File.mkdir_p!(bin)

    File.write!(Path.join(bin, "rela"), """
    #!/bin/sh
    if [ "$1" = version ]; then echo "#{version}"; exit 0; fi
    echo "time=2026-11-11T00:00:00Z level=WARN msg=noise"
    echo "✗ flows.letter.states.draft: refused by the stand-in"
    exit 1
    """)

    File.chmod!(Path.join(bin, "rela"), 0o755)
    System.put_env("ATLAS_RELA_BIN", bin)
  end

  # A diagram as gen writes it, without a rela to draw it.
  defp put_diagram(path, mermaid \\ "stateDiagram-v2\n") do
    File.mkdir_p!(Path.dirname(path))
    page = %{"name" => "letter", "label" => "Letter", "version" => "0", "mermaid" => mermaid}

    File.write!(
      path,
      AtlasFlowGenerator.Header.put(".md", "x.ex", AtlasFlowGenerator.Rela.diagram(page))
    )
  end

  describe "without rela" do
    test "writes flows.yaml with its header, and says that rela did not run", %{yaml: yaml} do
      gen()
      assert "# Generated by atlas (mix atlas.flow.gen) from " <> _ = File.read!(yaml)
      assert File.read!(yaml) =~ "test/support/example.ex. Do not edit"

      assert String.ends_with?(
               File.read!(yaml),
               AtlasFlowGenerator.Rela.flows_yaml(AtlasFlowGenerator.Example.__flows__())
             )

      assert_received {:mix_shell, :error, ["rela not run (ATLAS_RELA_BIN is not set)" <> _]}
    end

    test "writes flows.json with its header, every gate, and the hash of flows.yaml", c do
      gen()
      json = File.read!(c.json)
      assert AtlasFlowGenerator.Header.generated?(".json", json)
      assert json =~ "test/support/example.ex"
      data = JSON.decode!(json)
      assert data["rela_flows_sha256"] == AtlasFlowGenerator.Atlas.sha256(File.read!(c.yaml))
      assert Map.keys(data["gates"]) == ["proofread", "size_limit"]
      assert Map.keys(data["flows"]) == ["letter"]
    end

    test "--check fails on a hand edit of flows.json", %{json: json, diagram: d} do
      gen()
      put_diagram(d)
      gen(["--check"])
      File.write!(json, String.replace(File.read!(json), ~s("version": 2), ~s("version": 3)))
      assert_raise Mix.Error, ~r/out of date.*atlas\/flows.json/, fn -> gen(["--check"]) end
      gen()
      gen(["--check"])
    end

    test "a gate the subflows name in another version fails the task", %{json: json} do
      Application.put_env(:atlas_flow_generator, :gates, AtlasFlowGenerator.Example)
      assert_raise Mix.Error, ~r/flows.json: .*names gate proofread version 2/, fn -> gen() end
      refute File.exists?(json)
    end

    test "--check fails on a missing diagram, which it cannot draw", %{diagram: diagram} do
      gen()
      refute File.exists?(diagram)
      assert_raise Mix.Error, ~r/letter.md \(missing\)/, fn -> gen(["--check"]) end
    end

    test "--check passes on what it can check and says what it did not", %{diagram: diagram} do
      gen()
      put_diagram(diagram)
      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}
      assert_received {:mix_shell, :error, ["rela not run" <> rest]}
      assert rest =~ "diagrams were neither drawn nor compared"
    end

    test "an existing diagram is left as it is", %{diagram: diagram} do
      put_diagram(diagram, "old\n")
      gen()
      assert File.read!(diagram) =~ "old\n"
    end

    test "--check fails on a hand edit of flows.yaml and writes nothing", %{
      yaml: yaml,
      diagram: d
    } do
      gen()
      put_diagram(d)
      File.write!(yaml, String.replace(File.read!(yaml), "label: Letter", ~s(label: "Letter")))
      assert_raise Mix.Error, ~r/out of date.*rela\/flows.yaml/, fn -> gen(["--check"]) end
      assert File.read!(yaml) =~ ~s(label: "Letter")
    end

    test "--check fails on a stale file from an older contract", %{yaml: yaml, diagram: d} do
      gen()
      put_diagram(d)
      File.write!(yaml, AtlasFlowGenerator.Header.put(".yaml", "x.ex", "flows:\n"))
      assert_raise Mix.Error, ~r/rela\/flows.yaml/, fn -> gen(["--check"]) end
      gen()
      gen(["--check"])
    end

    test "generated files no subflow needs are left over, in both folders", %{tmp_dir: dir} = c do
      gen()
      put_diagram(c.diagram)
      old_yaml = Path.join(dir, "rela/old.yaml")
      old_md = Path.join(dir, "diagrams/gone.md")
      old_json = Path.join(dir, "atlas/old.json")
      File.write!(old_yaml, File.read!(c.yaml))
      File.write!(old_md, File.read!(c.diagram))
      File.write!(old_json, File.read!(c.json))

      assert_raise Mix.Error,
                   ~r/old.yaml \(left over\).*old.json \(left over\).*gone.md \(left over\)/,
                   fn -> gen(["--check"]) end

      gen()
      refute File.exists?(old_yaml)
      refute File.exists?(old_md)
      refute File.exists?(old_json)
    end

    test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, yaml: yaml} do
      File.mkdir_p!(Path.dirname(yaml))
      File.write!(yaml, "flows: {}\n")
      notes = Path.join(dir, "diagrams/notes.md")
      File.mkdir_p!(Path.dirname(notes))
      File.write!(notes, "# Notes\n")
      assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
      assert File.read!(yaml) == "flows: {}\n"
      File.rm!(yaml)
      gen()
      assert File.exists?(notes)
    end

    test "an unknown target fails before anything is written", %{tmp_dir: dir} do
      Application.put_env(:atlas_flow_generator, :targets, json: dir)
      assert_raise Mix.Error, ~r/unknown target :json/, fn -> gen() end
      assert File.ls!(dir) == []
    end
  end

  describe "with ATLAS_RELA_BIN set" do
    test "what rela refuses fails the task, in rela's words, and nothing is written", c do
      refusing_rela(c.tmp_dir)

      for args <- [[], ["--check"]] do
        error = assert_raise Mix.Error, fn -> gen(args) end
        assert error.message =~ "refused by the stand-in"
        refute error.message =~ "level=WARN"
      end

      refute File.exists?(c.yaml)
    end

    test "a rela that is not 26.11.2 is refused", c do
      refusing_rela(c.tmp_dir, "rela version 26.10.0")

      assert_raise Mix.Error, ~r/expected rela version 26.11.2.*got rela version 26.10.0/, fn ->
        gen()
      end
    end

    test "a folder without rela is refused", c do
      System.put_env("ATLAS_RELA_BIN", c.tmp_dir)
      assert_raise Mix.Error, ~r/ATLAS_RELA_BIN: no rela at/, fn -> gen(["--check"]) end
    end

    @tag :rela
    test "draws each diagram; --check then fails on a hand edit of it", c do
      System.put_env("ATLAS_RELA_BIN", c.real)
      gen()
      assert File.read!(c.diagram) =~ "```mermaid\nstateDiagram-v2\n"
      refute_received {:mix_shell, :error, ["rela not run" <> _]}
      gen(["--check"])
      assert_received {:mix_shell, :info, ["generated files are up to date"]}

      File.write!(c.diagram, File.read!(c.diagram) <> "extra\n")
      assert_raise Mix.Error, ~r/diagrams\/letter.md/, fn -> gen(["--check"]) end
      gen()
      gen(["--check"])
    end
  end

  test "the writers and the task read only a contract's data, not the format's internals" do
    # The format is lib/schema.ex and lib/schema/ (the composition); the rest only reads data.
    for path <-
          Path.wildcard("lib/**/*.ex") -- ["lib/schema.ex" | Path.wildcard("lib/schema/**/*.ex")] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")
      refute code =~ "AtlasFlowGenerator.Schema", "#{path} calls into AtlasFlowGenerator.Schema"
    end
  end
end
