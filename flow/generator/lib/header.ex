defmodule AtlasFlowGenerator.Header do
  @moduledoc """
  The first line of every generated file: it says the file is generated, by which
  command, and from which contract file. `mix atlas.flow.gen` writes it, never
  overwrites a file without it, and removes a file with it that it no longer writes.

  In YAML the line is a comment; Rela ignores comments, so the header does not change
  a flow's version. In Markdown it is an HTML comment, which renders as nothing.

  Copied in spirit from the BFF's header (`AtlasBFF.Header`); two small copies do not
  yet justify a shared dependency.
  """

  @marker "Generated by atlas"

  @doc "The header text, naming the contract file(s) the file is generated from."
  def text(source),
    do:
      "#{@marker} (mix atlas.flow.gen) from #{source}. Do not edit: change the contract and regenerate."

  @doc "`body`, a file of type `ext` (`.yaml` or `.md`), with its header line first."
  def put(ext, source, body), do: line(ext, text(source)) <> "\n" <> body

  @doc """
  Whether `content` starts with exactly the header `put/3` writes for a file of type
  `ext`, naming any source: only then may `mix atlas.flow.gen` replace or remove it.
  """
  def generated?(ext, content) when ext in [".yaml", ".md"] do
    [first | _] = String.split(content, "\n", parts: 2)
    [head, tail] = String.split(line(ext, text("FILE")), "FILE")

    byte_size(first) > byte_size(head) + byte_size(tail) and
      String.starts_with?(first, head) and String.ends_with?(first, tail)
  end

  def generated?(_ext, _content), do: false

  defp line(".yaml", text), do: "# " <> text
  defp line(".md", text), do: "<!-- " <> text <> " -->"
  defp line(ext, _text), do: raise(ArgumentError, "no header for #{ext} files")
end
