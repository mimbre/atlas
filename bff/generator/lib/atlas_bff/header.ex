defmodule AtlasBFF.Header do
  @moduledoc """
  The header of every generated file: it says the file is generated, by which command,
  and which contract file to change instead. `mix atlas.gen` writes it, never overwrites
  a file without it, and removes a file with it that no target writes any more.

  JSON has no comments: there the header is the object's first member, `"$comment"`.
  Swift has: there it is a `//` line, the first one, or the second one after a
  `// swift-tools-version:` line, which a package manifest must start with.
  """

  @marker "Generated by atlas"
  @tools_version "// swift-tools-version:"

  @doc "The header text, naming the contract file to change."
  def text(contract_file),
    do: "#{@marker} (mix atlas.gen). Do not edit: change #{contract_file} and regenerate."

  @doc "`body`, a file of type `ext`, with its header."
  def put(".json", contract_file, "{\n" <> members),
    do: "{\n  \"$comment\": #{JSON.encode!(text(contract_file))},\n" <> members

  def put(".swift", contract_file, @tools_version <> _ = body) do
    [tools, rest] = String.split(body, "\n", parts: 2)
    tools <> "\n// " <> text(contract_file) <> "\n" <> rest
  end

  def put(".swift", contract_file, body), do: "// " <> text(contract_file) <> "\n" <> body

  def put(ext, _contract_file, _body),
    do: raise(ArgumentError, "no header for #{ext} files")

  @doc """
  Whether `content` starts with exactly the header `put/3` writes for a file of type
  `ext`, naming any contract file: only then may `mix atlas.gen` replace or remove it.
  """
  def generated?(".json", content) do
    case String.split(content, "\n", parts: 3) do
      ["{", second | _] -> header_line?(second, ~s(  "$comment": #{JSON.encode!(text("FILE"))},))
      _ -> false
    end
  end

  def generated?(".swift", content) do
    case String.split(content, "\n", parts: 3) do
      [@tools_version <> _, second | _] -> header_line?(second, "// " <> text("FILE"))
      [first | _] -> header_line?(first, "// " <> text("FILE"))
    end
  end

  def generated?(_ext, _content), do: false

  # `line` is `template` with a nonempty file name in place of FILE.
  defp header_line?(line, template) do
    [head, tail] = String.split(template, "FILE")

    byte_size(line) > byte_size(head) + byte_size(tail) and
      String.starts_with?(line, head) and String.ends_with?(line, tail)
  end
end
