defmodule Mix.Tasks.Atlas.GenTest do
  # Sets the application's config, so not async.
  use ExUnit.Case

  @moduletag :tmp_dir

  setup %{tmp_dir: dir} do
    Application.put_env(:atlas_bff, :contract, AtlasBFF.Example)
    Application.put_env(:atlas_bff, :targets, json: dir)
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :targets], do: Application.delete_env(:atlas_bff, key)
      Mix.shell(Mix.Shell.IO)
    end)

    %{json: Path.join(dir, "blocks.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.Atlas.Gen.run(args)

  test "writes each file with its header; --check passes after", %{json: json} do
    gen()

    assert "{\n  \"$comment\": \"Generated by atlas (mix atlas.gen). Do not edit: change " <> _ =
             File.read!(json)

    assert File.read!(json) =~ "test/support/example.ex and regenerate."
    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "--check fails on a stale file and writes nothing", %{json: json} do
    gen()
    File.write!(json, String.replace(File.read!(json), "card", "kard"))
    assert_raise Mix.Error, ~r/out of date.*blocks.json/, fn -> gen(["--check"]) end
    assert File.read!(json) =~ "kard"
  end

  test "a file with the header that no target writes is left over", %{tmp_dir: dir} do
    gen()
    old = Path.join(dir, "old.json")
    File.write!(old, File.read!(Path.join(dir, "blocks.json")))
    assert_raise Mix.Error, ~r/old.json \(left over\)/, fn -> gen(["--check"]) end
    gen()
    refute File.exists?(old)
  end

  test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, json: json} do
    File.write!(json, "{\n  \"mine\": true\n}\n")
    readme = Path.join(dir, "notes.json")
    File.write!(readme, "{\n  \"note\": \"Generated by atlas, they say\"\n}\n")
    assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
    assert File.read!(json) =~ "mine"
    File.rm!(json)
    gen()
    assert File.exists?(readme)
  end

  test "an unknown target fails before anything is written", %{tmp_dir: dir} do
    Application.put_env(:atlas_bff, :targets, kotlin: dir)
    assert_raise Mix.Error, ~r/unknown target :kotlin; known: \[:json, :swift\]/, fn -> gen() end
    assert File.ls!(dir) == []
  end

  test "a target with options: the Swift package, each file with its header, checked", %{
    tmp_dir: dir
  } do
    swift = Path.join(dir, "swift")
    Application.put_env(:atlas_bff, :targets, json: dir, swift: {swift, package: "NeutralKit"})
    gen()
    manifest = File.read!(Path.join(swift, "Package.swift"))

    assert "// swift-tools-version: 6.0\n// Generated by atlas (mix atlas.gen). Do not edit: change " <>
             _ = manifest

    for path <- Path.wildcard(Path.join(swift, "**/*.swift")),
        Path.basename(path) != "Package.swift" do
      assert "// Generated by atlas (mix atlas.gen). Do not edit: change " <> _ = File.read!(path)
    end

    assert File.exists?(Path.join(swift, "Sources/NeutralKit/Blocks.swift"))
    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}

    # A fixture kept by hand is no generated file: neither stale nor left over.
    File.mkdir_p!(Path.join(swift, "Tests/Fixtures/front"))
    File.write!(Path.join(swift, "Tests/Fixtures/front/received.jsonl"), "{}\n")
    blocks = Path.join(swift, "Sources/NeutralKit/Blocks.swift")
    old = Path.join(swift, "Sources/NeutralKit/Old.swift")
    File.write!(old, File.read!(blocks))
    File.write!(blocks, File.read!(blocks) <> "// edited\n")

    assert_raise Mix.Error, ~r/out of date.*Blocks.swift.*Old.swift \(left over\)/, fn ->
      gen(["--check"])
    end

    gen()
    refute File.exists?(old)
    assert File.exists?(Path.join(swift, "Tests/Fixtures/front/received.jsonl"))
    gen(["--check"])
  end

  test "a target given neither a folder nor {folder, options} fails", %{tmp_dir: dir} do
    Application.put_env(:atlas_bff, :targets, swift: {dir})
    assert_raise Mix.Error, ~r/expected a folder or \{folder, options\}/, fn -> gen() end
  end

  test "the targets read only a contract's data, not the schema's internals" do
    for path <- Path.wildcard("lib/**/*.ex") -- ["lib/atlas_bff/schema.ex"] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")
      refute code =~ "AtlasBFF.Schema.", "#{path} calls into AtlasBFF.Schema"
    end
  end
end
